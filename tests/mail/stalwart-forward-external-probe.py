import urllib.request

CORE = "urn:ietf:params:jmap:core"
MAIL = "urn:ietf:params:jmap:mail"
SIEVE = "urn:ietf:params:jmap:sieve"
REGISTRY = "urn:stalwart:jmap"
HERE = os.path.dirname(os.path.abspath(__file__))
GOLDENS = os.path.join(HERE, "forward-goldens")
GOLDEN_HOST = "mail.brand.test"
GOLDEN_DEST = "me@outside.test"
# Must match crates/k2-daemon/src/mail/sieve_lockdown.rs SIEVE_WRITE_PERMISSIONS.
SIEVE_WRITE = ["jmapSieveScriptCreate", "jmapSieveScriptUpdate", "jmapSieveScriptDestroy",
               "sievePutScript", "sieveSetActive", "sieveDeleteScript", "sieveRenameScript"]

FAILED = []


def check(step, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {step}: {detail}", flush=True)
    if not ok:
        FAILED.append(step)


def info(step, detail=""):
    print(f"[INFO] {step}: {detail}", flush=True)


class Client:
    def __init__(self, base, basic=None, bearer=None):
        self.base = base.rstrip("/")
        self.auth = ("Basic " + base64.b64encode(f"{basic[0]}:{basic[1]}".encode()).decode()) if basic else f"Bearer {bearer}"
        self._session = None

    def _req(self, method, url, body=None, raw=None, ctype="application/json"):
        url = url if url.startswith("http") else self.base + url
        data = raw if raw is not None else (json.dumps(body).encode() if body is not None else None)
        req = urllib.request.Request(url, data=data, method=method)
        req.add_header("Authorization", self.auth)
        if data is not None:
            req.add_header("Content-Type", ctype)
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                out = r.read()
                try:
                    return r.status, json.loads(out or b"null")
                except ValueError:
                    return r.status, out
        except urllib.error.HTTPError as e:
            return e.code, {"httpError": e.code, "body": e.read().decode(errors="replace")[:300]}

    def session(self):
        if self._session is None:
            st, doc = self._req("GET", "/jmap/session")
            if st != 200:
                raise RuntimeError(f"session HTTP {st}: {doc}")
            self._session = doc
        return self._session

    def path(self, key):
        p = self.session()[key]
        return "/" + p.split("://", 1)[1].split("/", 1)[1] if p.startswith("http") else p

    def own_account(self):
        prim = self.session().get("primaryAccounts", {})
        return prim.get(REGISTRY) or prim.get(MAIL) or next(iter(self.session()["accounts"]))

    def call(self, method, args, using=(CORE, REGISTRY)):
        if "accountId" not in args:
            args = dict(args, accountId=self.own_account())
        st, resp = self._req("POST", self.path("apiUrl"), {"using": list(using), "methodCalls": [[method, args, "0"]]})
        if st != 200:
            return "http", resp
        first = resp["methodResponses"][0]
        return first[0], first[1]

    def upload(self, account, data):
        st, resp = self._req("POST", self.path("uploadUrl").replace("{accountId}", account), raw=data, ctype="application/sieve")
        if st not in (200, 201) or not isinstance(resp, dict) or "blobId" not in resp:
            return None, f"upload HTTP {st}: {resp}"
        return resp["blobId"], None


# ── the loopback "outside" ──────────────────────────────────────────

class Sink:
    """A minimal SMTP server on 127.0.0.1 that records every message."""

    def __init__(self):
        self.got = []
        self.lock = threading.Lock()
        self.srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.srv.bind(("127.0.0.1", 0))
        self.srv.listen(16)
        self.port = self.srv.getsockname()[1]
        threading.Thread(target=self._serve, daemon=True).start()

    def _serve(self):
        while True:
            try:
                c, _ = self.srv.accept()
            except OSError:
                return
            threading.Thread(target=self._one, args=(c,), daemon=True).start()

    def _one(self, c):
        f = c.makefile("rb")
        send = lambda s: c.sendall(s.encode() + b"\r\n")
        send("220 sink.outside.test ESMTP")
        mail_from, rcpt = None, []
        try:
            while True:
                line = f.readline()
                if not line:
                    return
                cmd = line.decode(errors="replace").strip()
                up = cmd.upper()
                if up.startswith("EHLO") or up.startswith("HELO"):
                    c.sendall(b"250-sink.outside.test\r\n250-8BITMIME\r\n250 SMTPUTF8\r\n")
                elif up.startswith("MAIL FROM:"):
                    mail_from = cmd[10:].strip().split(" ")[0].strip("<>")
                    rcpt = []
                    send("250 ok")
                elif up.startswith("RCPT TO:"):
                    rcpt.append(cmd[8:].strip().split(" ")[0].strip("<>").lower())
                    send("250 ok")
                elif up == "DATA":
                    send("354 go")
                    data = []
                    while True:
                        l = f.readline()
                        if not l or l.rstrip(b"\r\n") == b".":
                            break
                        data.append(l[1:] if l.startswith(b"..") else l)
                    with self.lock:
                        self.got.append({"from": mail_from, "rcpt": rcpt, "data": b"".join(data).decode(errors="replace")})
                    send("250 queued")
                elif up == "QUIT":
                    send("221 bye")
                    return
                else:
                    send("250 ok")
        finally:
            c.close()

    def with_id(self, mid):
        with self.lock:
            return [m for m in self.got if mid in m["data"]]


def wait_for(pred, secs=40):
    end = time.time() + secs
    while time.time() < end:
        v = pred()
        if v:
            return v
        time.sleep(0.5)
    return pred()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--url", required=True)
    ap.add_argument("--domain")
    ap.add_argument("--smtp-port", type=int, default=20025)
    ap.add_argument("--host", default="mail.example.test", help="the box's mail host name (authserv-id)")
    args = ap.parse_args()
    cred = os.environ.get("STALWART_PROBE_ADMIN", "")
    if ":" not in cred:
        sys.exit("set STALWART_PROBE_ADMIN=<admin user>:<secret> in the environment")
    admin_user, admin_pw = cred.split(":", 1)
    domain = args.domain or admin_user.split("@", 1)[-1]
    tag = secrets.token_hex(3)
    admin = Client(args.url, basic=(admin_user, admin_pw))
    n, a = admin.call("x:Domain/query", {"filter": {"name": domain}})
    if n != "x:Domain/query" or not a.get("ids"):
        sys.exit(f"domain {domain} not found: {n} {a}")
    did = a["ids"][0]
    sink = Sink()
    info("fixture", f"domain {domain}; host {args.host}; sink 127.0.0.1:{sink.port}; run {tag}")
    made, routes = [], []

    def account(name, perms=None, admin_role=False):
        pw = secrets.token_urlsafe(24)
        acct = {"@type": "User", "name": name, "domainId": did, "credentials": {"0": {"@type": "Password", "secret": pw}}}
        if admin_role:
            acct["roles"] = {"@type": "Admin"}
        else:
            acct["quotas"] = {"maxDiskQuota": 104857600, "maxEmails": 1000}
        if perms is not None:
            acct["permissions"] = perms
        n, a = admin.call("x:Account/set", {"create": {"k": acct}})
        cid = ((a.get("created") or {}).get("k") or {}).get("id") if n == "x:Account/set" else None
        if not cid:
            sys.exit(f"account {name}: {n} {json.dumps(a)[:300]}")
        made.append(cid)
        return cid, pw

    lock = {"@type": "Merge", "enabledPermissions": {}, "disabledPermissions": {p: True for p in SIEVE_WRITE}}
    svc_id, _ = account(f"k2fx-svc-{tag}", admin_role=True)
    n, a = admin.call("x:ApiKey/set", {"accountId": svc_id, "create": {"k": {"description": "k2", "permissions": {"@type": "Inherit"}, "allowedIps": {}}}})
    key = ((a.get("created") or {}).get("k") or {}).get("secret")
    if not key:
        sys.exit(f"service key: {n} {json.dumps(a)[:300]}")
    svc = Client(args.url, bearer=key)
    alice, alice_pw = account(f"k2fx-alice-{tag}", lock)
    bob, _ = account(f"k2fx-bob-{tag}", lock)
    alice_addr, bob_addr = f"k2fx-alice-{tag}@{domain}", f"k2fx-bob-{tag}@{domain}"

    # The "outside": outside.test → the sink (a relay route, prepended).
    n, a = admin.call("x:MtaRoute/set", {"create": {"r": {"@type": "Relay", "name": f"k2fxsink{tag}", "address": "127.0.0.1",
                                                           "port": sink.port, "protocol": "smtp", "implicitTls": False}}})
    rid = ((a.get("created") or {}).get("r") or {}).get("id")
    if not rid:
        sys.exit(f"sink route: {n} {json.dumps(a)[:300]}")
    routes.append(rid)
    n, g = admin.call("x:MtaOutboundStrategy/get", {"ids": ["singleton"]})
    old_route = g["list"][0]["route"]
    m = dict((old_route.get("match") or {}))
    shifted = {str(int(k) + 1): v for k, v in m.items()}
    shifted["0"] = {"if": "rcpt_domain == 'outside.test'", "then": f"'k2fxsink{tag}'"}
    n, a = admin.call("x:MtaOutboundStrategy/set", {"update": {"singleton": {"route": {"match": shifted, "else": old_route["else"]}}}})
    if a.get("notUpdated"):
        sys.exit(f"route bind: {json.dumps(a)[:300]}")
    # The sandbox's inbound listener isn't on :25, and Stalwart's stock rule
    # asks for auth on any other port (`local_port != 25`): make the sandbox
    # port the "inbound" one, as :25 is on a real box (the p4b probe's fix).
    n, ls = admin.call("x:NetworkListener/get", {"ids": None})
    for l in ls.get("list") or []:
        if (l.get("protocol") or "").lower() == "smtp" and l.get("name") == "smtp":
            args.smtp_port = int(next(iter(l["bind"])).rsplit(":", 1)[1])
    n, a = admin.call("x:MtaStageAuth/set", {"update": {"singleton": {"require": {"else": f"local_port != {args.smtp_port}"}}}})
    info("sandbox: inbound auth rule moved to the sandbox port", f"{args.smtp_port}: {n} {json.dumps(a)[:160]}")
    # 0.16.10 refuses every reload while downloaded spam rules call
    # `bit_and` (K2's A4 repair rewrites them on a real box); drop them here.
    n, q = admin.call("x:SpamDnsblServer/query", {})
    if q.get("ids"):
        n, g = admin.call("x:SpamDnsblServer/get", {"ids": q["ids"]})
        bad = [x["id"] for x in (g.get("list") or []) if "bit_and" in json.dumps(x)]
        if bad:
            admin.call("x:SpamDnsblServer/set", {"destroy": bad})
    n, a = admin.call("x:Action/set", {"create": {"r": {"@type": "ReloadSettings"}}})
    info("sandbox: reload", f"{n} {json.dumps(a)[:120]}")

    def golden(name, dest, host):
        src = open(os.path.join(GOLDENS, name)).read()
        return src.replace(GOLDEN_HOST, host).replace(GOLDEN_DEST, dest).replace("sales@brand.test", alice_addr)

    def put_script(account_id, src):
        blob, err = svc.upload(account_id, src.encode())
        if not blob:
            return "upload", {"error": err}
        n, a = svc.call("SieveScript/get", {"accountId": account_id, "ids": None}, using=(CORE, SIEVE))
        existing = [s["id"] for s in (a.get("list") or []) if s.get("name") == "k2"]
        if existing:
            return svc.call("SieveScript/set", {"accountId": account_id, "update": {existing[0]: {"blobId": blob}},
                                                "onSuccessActivateScript": existing[0]}, using=(CORE, SIEVE))
        return svc.call("SieveScript/set", {"accountId": account_id, "create": {"k": {"name": "k2", "blobId": blob}},
                                            "onSuccessActivateScript": "#k"}, using=(CORE, SIEVE))

    # ── X1 every golden compiles ────────────────────────────────────
    for name in sorted(os.listdir(GOLDENS)):
        src = golden(name, "x@outside.test", args.host)
        blob, err = svc.upload(alice, src.encode())
        n, a = svc.call("SieveScript/validate", {"accountId": alice, "blobId": blob}, using=(CORE, SIEVE)) if blob else ("upload", err)
        check(f"X1 {name} compiles", n == "SieveScript/validate" and a.get("error") is None, f"{n} {json.dumps(a)[:300]}")

    def inject(mid, mail_from, extra_headers="", body="Hello from outside.\r\n", to=None):
        to = to or alice_addr
        msg = (f"From: Sender <sender@sender.example>\r\nTo: {to}\r\nSubject: probe {mid}\r\n"
               f"Message-ID: <{mid}@sender.example>\r\nDate: {time.strftime('%a, %d %b %Y %H:%M:%S +0000', time.gmtime())}\r\n"
               f"{extra_headers}MIME-Version: 1.0\r\nContent-Type: text/plain\r\n\r\n{body}")
        with smtplib.SMTP("127.0.0.1", args.smtp_port, local_hostname="sender.example", timeout=30) as s:
            refused = s.sendmail(mail_from, [to], msg.encode())
        info(f"inject {mid}", f"refused {refused}")

    def ids_for(mid, account=None):
        n, a = svc.call("Email/query", {"accountId": account or alice, "filter": {"subject": f"probe {mid}"}}, using=(CORE, MAIL))
        return (a.get("ids") or []) if n == "Email/query" else None

    def kept(mid, account=None):
        ids = ids_for(mid, account)
        return -1 if ids is None else len(ids)

    def stored_headers(mid, account=None):
        ids = ids_for(mid, account) or []
        if not ids:
            return {}
        n, e = svc.call("Email/get", {"accountId": account or alice, "ids": ids[:1], "properties": [
            "header:X-Spam-Score:asText", "header:X-K2-Forwarded:asText", "header:Authentication-Results:asText", "mailboxIds"]},
            using=(CORE, MAIL))
        return (e.get("list") or [{}])[0]

    def kept_eventually(mid):
        return wait_for(lambda: kept(mid) > 0, 20) and kept(mid) > 0

    # ── X0 control: a bare K2 same-box-style redirect to the sink ────
    # Separates the sandbox (inbound, the relay route to the sink) from
    # the guard: if this one doesn't reach the sink, the setup is at fault.
    n, a = put_script(bob, 'require ["copy"];\n# k2-forward\nredirect :copy "me@outside.test";\n')
    mid = f"x0-{tag}"
    inject(mid, "sender@sender.example", to=bob_addr)
    got = wait_for(lambda: sink.with_id(mid))
    check("X0 control: an unguarded redirect reaches the loopback sink", len(got) == 1,
          f"{len(got)} at the sink; bob kept {kept(mid, bob)}; headers {json.dumps(stored_headers(mid, bob))[:300]}")
    if not got:
        n, q = admin.call("x:QueuedMessage/query", {})
        ids = (q.get("ids") or [])[:10]
        n, g = admin.call("x:QueuedMessage/get", {"ids": ids}) if ids else (n, q)
        info("diag queue after X0", f"{n} {json.dumps(g)[:1200]}")

    # ── keep on ─────────────────────────────────────────────────────
    n, a = put_script(alice, golden("external-keep.sieve", "me@outside.test", args.host))
    check("X1 K2's service account writes the guarded script", n == "SieveScript/set" and not a.get("notCreated") and not a.get("notUpdated"), f"{n} {json.dumps(a)[:200]}")

    mid = f"x2-{tag}"
    inject(mid, "sender@sender.example")
    got = wait_for(lambda: sink.with_id(mid))
    check("X2 a plain message is forwarded to the outside", len(got) == 1, f"{len(got)} at the sink")
    if got:
        check("X2 MAIL FROM is the forwarding mailbox (forwarder return path)", (got[0]["from"] or "").lower() == alice_addr.lower(), got[0]["from"])
        check("X2 the forwarded copy carries this box's marker", f"X-K2-Forwarded: {args.host}" in got[0]["data"], "")
        check("X2 the original From is untouched", "From: Sender <sender@sender.example>" in got[0]["data"], "")
    check("X2 the mailbox keeps its copy (keep on)", kept_eventually(mid), f"stored headers {json.dumps(stored_headers(mid))[:400]}")
    if not got or kept(mid) <= 0:
        # Diagnostics: what the mailbox holds, what the queue holds.
        n, a = svc.call("Email/query", {"accountId": alice}, using=(CORE, MAIL))
        info("diag alice Email/query", f"{n} {json.dumps(a)[:400]}")
        n, q = admin.call("x:QueuedMessage/query", {})
        ids = (q.get("ids") or [])[:10]
        n, g = admin.call("x:QueuedMessage/get", {"ids": ids, "properties": ["id", "returnPath", "recipients"]}) if ids else (n, q)
        info("diag queue", f"{n} {json.dumps(g)[:800]}")

    for step, mid, frm, hdr, body in [
        ("X3 a bounce (empty MAIL FROM) stays home", f"x3-{tag}", "", "", "Delivery failed.\r\n"),
        ("X4 a message with this box's marker stays home", f"x4-{tag}", "sender@sender.example", f"X-K2-Forwarded: {args.host}\r\n", "Hi.\r\n"),
        ("X5 this box's dmarc=fail stays home", f"x5-{tag}", "sender@sender.example",
         f"Authentication-Results: {args.host};\r\n\tdkim=none; spf=none; dmarc=fail (p=reject) header.from=sender.example\r\n", "Hi.\r\n"),
    ]:
        inject(mid, frm, hdr, body)
        kept_ok = kept_eventually(mid)
        time.sleep(3)
        check(step, kept_ok and not sink.with_id(mid), f"kept {kept(mid)}, at sink {len(sink.with_id(mid))}; {json.dumps(stored_headers(mid))[:200]}")

    # X6 spam: GTUBE.
    mid = f"x6-{tag}"
    inject(mid, "sender@sender.example", "", "XJS*C4JDBQADN1.NSBN3*2IDNEN*GTUBE-STANDARD-ANTI-UBE-TEST-EMAIL*C.34X\r\n")
    kept_ok = kept_eventually(mid)
    time.sleep(3)
    spam_hdr = (stored_headers(mid).get("header:X-Spam-Score:asText") or "").strip()
    if spam_hdr.lower().startswith("spam"):
        check("X6 spam stays home", kept_ok and not sink.with_id(mid), f"X-Spam-Score: {spam_hdr}; at sink {len(sink.with_id(mid))}")
    else:
        info("X6 GTUBE not scored as spam on this Stalwart; spam stop not exercised", f"X-Spam-Score: {spam_hdr!r}; at sink {len(sink.with_id(mid))}")

    # ── keep off (with an out-of-office block first) ────────────────
    n, a = put_script(alice, golden("external-nokeep-ooo.sieve", "me@outside.test", args.host))
    check("X7 the keep-off script (after OOO) is written", n == "SieveScript/set" and not a.get("notUpdated"), f"{n} {json.dumps(a)[:200]}")
    mid = f"x7-{tag}"
    inject(mid, "sender@sender.example")
    got = wait_for(lambda: sink.with_id(mid))
    time.sleep(3)
    check("X7 keep off: forwarded", len(got) == 1, f"{len(got)} at the sink")
    check("X7 keep off: not kept", kept(mid) == 0, f"kept {kept(mid)}")

    # ── X8 the mailbox itself still can't write Sieve ───────────────
    user = Client(args.url, basic=(alice_addr, alice_pw))
    blob, err = user.upload(alice, b'redirect "exfil@outside.test";\r\n')
    n, a = user.call("SieveScript/set", {"accountId": alice, "create": {"x": {"name": "mine", "blobId": blob}}, "onSuccessActivateScript": "#x"},
                     using=(CORE, SIEVE)) if blob else ("upload", {"error": err})
    check("X8 a mailbox login can't SieveScript/set", n in ("error", "http", "upload") or not a.get("created"), f"{n} {json.dumps(a)[:200]}")

    # ── X9 the two throttles K2 writes ──────────────────────────────
    throttle_file = os.path.join(GOLDENS, "..", "forward-throttles.json")
    if os.path.exists(throttle_file):
        for i, t in enumerate(json.load(open(throttle_file))):
            t = dict(t, name=f"{t.get('name', 'k2-forward')}-{tag}")
            n, a = admin.call("x:MtaOutboundThrottle/set", {"create": {f"t{i}": t}})
            tid = ((a.get("created") or {}).get(f"t{i}") or {}).get("id")
            check(f"X9 throttle {t['name']} accepted", bool(tid), f"{n} {json.dumps(a)[:300]}")
            if tid:
                admin.call("x:MtaOutboundThrottle/set", {"destroy": [tid]})
    else:
        info("X9 throttles", "tests/mail/forward-throttles.json not present; skipped")

    # ── cleanup ─────────────────────────────────────────────────────
    admin.call("x:MtaOutboundStrategy/set", {"update": {"singleton": {"route": old_route}}})
    for r in routes:
        admin.call("x:MtaRoute/set", {"destroy": [r]})
    for aid in made:
        admin.call("x:Account/set", {"destroy": [aid]})
    print(f"== outside forwards: {len(FAILED)} failed check(s): {FAILED} ==", flush=True)
    sys.exit(1 if FAILED else 0)


if __name__ == "__main__":
    main()
