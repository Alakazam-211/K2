#!/usr/bin/env node
// Builds sdk/server/dist: the JavaScript + .d.ts that K2 packs into the
// `@k2/server` npm tarball every daemon carries (`k2 app sdk add`).
//
// Why a committed dist: Node strips TypeScript types only OUTSIDE
// node_modules (ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING), so an App
// that installs @k2/server needs plain .js; and a consumer's tsc needs .d.ts
// (the sources import './x.ts'). The daemon embeds these files with
// include_str! (crates/k2-core/src/app_sdk/k2_server.rs) and packs them at
// K2's own version, so `cargo build` never needs node.
//
//   node scripts/sdk-server-dist.mjs          write sdk/server/dist
//   node scripts/sdk-server-dist.mjs --check  exit 1 if dist is stale
//
// dist/SOURCES lists the sha256 of every input (`<sha>  <path>`): the Rust
// freshness test (k2-core `app_sdk::k2_server`) fails when a source changed
// and dist was not rebuilt. Needs the repo's devDependencies (bun install).

import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SDK = join(ROOT, 'sdk')
const SERVER = join(SDK, 'server')
export const DIST = join(SERVER, 'dist')

function loadTs() {
  const req = createRequire(join(ROOT, 'package.json'))
  try {
    return req('typescript')
  } catch (e) {
    console.error(`sdk-server-dist: TypeScript is not installed (${e.message}); run bun install at the repo root`)
    process.exit(2)
  }
}

const posix = (p) => p.split(sep).join('/')

/** Build every dist file in memory: Map<path relative to dist, text>. */
export function buildDist() {
  const ts = loadTs()
  const cfgPath = join(SERVER, 'tsconfig.json')
  const cfg = ts.readConfigFile(cfgPath, ts.sys.readFile)
  if (cfg.error) throw new Error(ts.flattenDiagnosticMessageText(cfg.error.messageText, '\n'))
  const parsed = ts.parseJsonConfigFileContent(cfg.config, ts.sys, SERVER)
  const roots = parsed.fileNames.filter((f) => posix(relative(SERVER, f)).startsWith('src/'))
  const options = {
    ...parsed.options,
    noEmit: false,
    declaration: true,
    emitDeclarationOnly: false,
    rewriteRelativeImportExtensions: true,
    outDir: DIST,
    rootDir: SDK,
    sourceMap: false,
    declarationMap: false,
    removeComments: false,
    newLine: ts.NewLineKind.LineFeed,
  }
  const program = ts.createProgram(roots, options)
  const diags = ts.getPreEmitDiagnostics(program)
  if (diags.length) {
    const host = { getCanonicalFileName: (f) => f, getCurrentDirectory: () => ROOT, getNewLine: () => '\n' }
    throw new Error(ts.formatDiagnostics(diags, host))
  }
  const out = new Map()
  const res = program.emit(undefined, (file, text) => {
    out.set(posix(relative(DIST, file)), text)
  })
  if (res.emitSkipped) throw new Error('tsc skipped the emit')
  // Every input the dist was built from, outside node_modules.
  const inputs = program
    .getSourceFiles()
    .map((s) => s.fileName)
    .filter((f) => !f.includes('/node_modules/') && f.startsWith(posix(SDK) + '/'))
    .map((f) => posix(relative(ROOT, f)))
    .sort()
  inputs.push('sdk/server/tsconfig.json')
  const lines = inputs.map((p) => `${createHash('sha256').update(readFileSync(join(ROOT, p))).digest('hex')}  ${p}`)
  out.set(
    'SOURCES',
    '# GENERATED by scripts/sdk-server-dist.mjs: the sha256 of every input of sdk/server/dist.\n' +
      '# Stale? run `node scripts/sdk-server-dist.mjs` (the k2-core freshness test checks this).\n' +
      lines.join('\n') +
      '\n',
  )
  return out
}

function listDist(dir = DIST, base = DIST, acc = []) {
  if (!existsSync(dir)) return acc
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) listDist(p, base, acc)
    else acc.push(posix(relative(base, p)))
  }
  return acc.sort()
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  const want = buildDist()
  const have = listDist()
  const stale = []
  for (const [p, text] of want) {
    const f = join(DIST, p)
    if (!existsSync(f) || readFileSync(f, 'utf8') !== text) stale.push(p)
  }
  const extra = have.filter((p) => !want.has(p))
  if (check) {
    if (stale.length || extra.length) {
      console.error(`sdk-server-dist --check: stale ${JSON.stringify(stale)} extra ${JSON.stringify(extra)}; run node scripts/sdk-server-dist.mjs`)
      process.exit(1)
    }
    console.log('sdk-server-dist: dist is fresh')
  } else {
    for (const p of extra) rmSync(join(DIST, p))
    for (const [p, text] of want) {
      mkdirSync(dirname(join(DIST, p)), { recursive: true })
      writeFileSync(join(DIST, p), text)
    }
    console.log(`sdk-server-dist: wrote ${want.size} files (${stale.length} changed, ${extra.length} removed)`)
  }
}
