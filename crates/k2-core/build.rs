//! Build script for `k2-core`.
//!
//! It lists the Garden catalog (`src/zen/garden-catalog/*.toml`,
//! prd-zen-user-widgets-v2 R5) as `GARDEN_CATALOG_SOURCES`, so adding a
//! ready-made Garden is a data file with no Rust edit. See
//! `src/zen/garden_catalog.rs`. The functions below `main` embed the SDK
//! server files, the agent templates and the migrations list the same way.
//!
//! It also sets `cfg(k2_no_bash)` for a brand with `[cli] no_bash` true
//! (`k2_brand::CLI_NO_BASH`): such a build carries no shell CLI, so
//! `cli_stage` never compiles `cli/k2` in.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = manifest.join("src/zen/garden-catalog");
    println!("cargo:rerun-if-changed=build.rs");
    // A directory path makes cargo rerun on any change inside it (add,
    // remove, edit).
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut files: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path())
        .filter(|p| p.extension().is_some_and(|x| x == "toml"))
        .map(|p| {
            let name = p.file_name().and_then(|n| n.to_str()).expect("catalog file names are UTF-8").to_string();
            (name, p)
        })
        .collect();
    files.sort();

    let mut out = String::from(
        "/// Every `src/zen/garden-catalog/*.toml`, sorted by file name: `(file, TOML)`.\n\
         /// Generated by `build.rs`.\n\
         pub const GARDEN_CATALOG_SOURCES: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &files {
        let path = path.to_str().expect("catalog paths are UTF-8");
        writeln!(out, "    ({name:?}, include_str!({path:?})),").expect("write to String");
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("zen_garden_catalog.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));

    sdk_server_dist(&manifest);
    agent_templates(&manifest);
    migrations_list(&manifest);
    no_bash();
}

/// `cfg(k2_no_bash)` when the brand carries no shell CLI. A `cfg`, not an
/// `if` on the const: the script's bytes must not reach the binary at all.
fn no_bash() {
    println!("cargo:rerun-if-env-changed=K2_BRAND_DIR");
    println!("cargo::rustc-check-cfg=cfg(k2_no_bash)");
    if k2_brand::CLI_NO_BASH {
        println!("cargo::rustc-cfg=k2_no_bash");
    }
}

/// The migrations as `MIGRATIONS: &[(name, SQL)]`, in the order of
/// `drizzle_sql/ORDER`. Today only a test includes it, to prove it equals
/// the list written by hand in `src/db/mod.rs`; the runner still reads the
/// hand list. The build stops when ORDER and the folder disagree.
fn migrations_list(manifest: &std::path::Path) {
    let dir = manifest.join("drizzle_sql");
    let order_path = dir.join("ORDER");
    println!("cargo:rerun-if-changed={}", order_path.display());
    println!("cargo:rerun-if-changed={}", dir.display());

    let order = std::fs::read_to_string(&order_path).unwrap_or_else(|e| panic!("{}: {e}", order_path.display()));
    let mut sql_files: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path())
        .filter(|p| p.extension().is_some_and(|x| x == "sql"))
        .map(|p| p.file_stem().and_then(|n| n.to_str()).expect("migration file names are UTF-8").to_string())
        .collect();
    sql_files.sort();

    let names = match check_migrations_order(&order, &sql_files) {
        Ok(names) => names,
        Err(why) => panic!("{}: {why}", order_path.display()),
    };

    let mut out = String::from(
        "/// Every migration in apply order: `(name, SQL)`.\n\
         /// Generated by `build.rs` from `drizzle_sql/ORDER`.\n\
         pub(crate) const MIGRATIONS: &[(&str, &str)] = &[\n",
    );
    for name in &names {
        let path = dir.join(format!("{name}.sql"));
        let path = path.to_str().expect("migration paths are UTF-8");
        writeln!(out, "    ({name:?}, include_str!({path:?})),").expect("write to String");
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("migrations_list.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}

/// Read ORDER (one migration name per line; blank lines and `#` lines are
/// skipped) and check it against the `.sql` files in the folder (their
/// names without `.sql`). Returns the names in ORDER's order, or what is
/// wrong and on which line:
/// - a name that is not `NNNN_words` (four digits, `_`, then a-z 0-9 `_`);
/// - a name that is there twice;
/// - a four-digit number that is there twice;
/// - a name with no `.sql` file;
/// - a `.sql` file with no line.
fn check_migrations_order(order: &str, sql_files: &[String]) -> Result<Vec<String>, String> {
    // (name, its line in ORDER), in ORDER's order.
    let mut seen: Vec<(&str, usize)> = Vec::new();
    for (i, raw) in order.lines().enumerate() {
        let line = i + 1;
        let name = raw.trim();
        if name.is_empty() || name.starts_with('#') {
            continue;
        }
        if !is_migration_name(name) {
            return Err(format!("line {line}: `{name}` is not a migration name (four digits, `_`, then a-z 0-9 `_`)"));
        }
        if let Some((_, first)) = seen.iter().find(|(n, _)| *n == name) {
            return Err(format!("line {line}: `{name}` is already on line {first}"));
        }
        if let Some((other, first)) = seen.iter().find(|(n, _)| n[..4] == name[..4]) {
            return Err(format!("line {line}: `{name}` has the number of `{other}` on line {first}; a number is used once"));
        }
        if !sql_files.iter().any(|f| f == name) {
            return Err(format!("line {line}: there is no drizzle_sql/{name}.sql"));
        }
        seen.push((name, line));
    }
    if let Some(file) = sql_files.iter().find(|f| !seen.iter().any(|(n, _)| n == f)) {
        return Err(format!("drizzle_sql/{file}.sql has no line; add `{file}` as a new last line"));
    }
    Ok(seen.into_iter().map(|(n, _)| n.to_string()).collect())
}

/// `NNNN_words`: four digits, `_`, then one or more of a-z, 0-9, `_`.
fn is_migration_name(name: &str) -> bool {
    let b = name.as_bytes();
    b.len() > 5
        && b[..4].iter().all(u8::is_ascii_digit)
        && b[4] == b'_'
        && b[5..].iter().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == b'_')
}

/// Built-in agent templates (prd-agent-templates-v1 §2.2): every folder of
/// `agent-templates/` but `_*` is one template, embedded file by file as
/// `AGENT_TEMPLATE_SOURCES: &[(id, &[(path in the folder, text)])]`. The
/// shared "Working with your person and the team" block is
/// `AGENT_TEMPLATE_SHARED_BLOCK`; "Your first conversation" (templates with
/// `[[questions]]`) is `AGENT_TEMPLATE_FIRST_CONVERSATION`. The loader validates every file (its
/// paths, its TOML, its placeholders) at runtime and in a test; this only
/// refuses a symlink, which a template may never hold (AT4).
fn agent_templates(manifest: &std::path::Path) {
    let dir = manifest.join("agent-templates");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut ids: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path())
        .filter(|p| p.is_dir())
        .map(|p| (p.file_name().and_then(|n| n.to_str()).expect("template folder names are UTF-8").to_string(), p))
        .filter(|(n, _)| !n.starts_with('_'))
        .collect();
    ids.sort();
    let mut out = String::from(
        "/// Every built-in agent template: `(id, [(path in its folder, text)])`,\n\
         /// sorted. Generated by `build.rs` from `agent-templates/`.\n\
         pub const AGENT_TEMPLATE_SOURCES: &[(&str, &[(&str, &str)])] = &[\n",
    );
    for (id, path) in &ids {
        let mut files = Vec::new();
        walk_no_links(path, path, &mut files);
        files.sort();
        writeln!(out, "    ({id:?}, &[").expect("write to String");
        for (rel, file) in &files {
            let file = file.to_str().expect("template paths are UTF-8");
            writeln!(out, "        ({rel:?}, include_str!({file:?})),").expect("write to String");
        }
        out.push_str("    ]),\n");
    }
    out.push_str("];\n");
    let shared = dir.join("_shared/working-with-your-person.md");
    assert!(shared.is_file(), "{} is missing", shared.display());
    writeln!(
        out,
        "/// The shared block `shared_block = true` appends. Generated by `build.rs`.\npub const AGENT_TEMPLATE_SHARED_BLOCK: &str = include_str!({:?});",
        shared.to_str().expect("UTF-8")
    )
    .expect("write to String");
    let first = dir.join("_shared/first-conversation.md");
    assert!(first.is_file(), "{} is missing", first.display());
    writeln!(
        out,
        "/// The \"Your first conversation\" block a template with `[[questions]]` gets. Generated by `build.rs`.\npub const AGENT_TEMPLATE_FIRST_CONVERSATION: &str = include_str!({:?});",
        first.to_str().expect("UTF-8")
    )
    .expect("write to String");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("agent_templates.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}

fn walk_no_links(dir: &std::path::Path, base: &std::path::Path, acc: &mut Vec<(String, PathBuf)>) {
    for e in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())) {
        let p = e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path();
        let meta = std::fs::symlink_metadata(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()));
        assert!(!meta.file_type().is_symlink(), "{}: an agent template may not hold a symlink", p.display());
        if meta.is_dir() {
            println!("cargo:rerun-if-changed={}", p.display());
            walk_no_links(&p, base, acc);
        } else {
            let rel = p.strip_prefix(base).expect("under the template").components().map(|c| c.as_os_str().to_str().expect("UTF-8")).collect::<Vec<_>>().join("/");
            acc.push((rel, p));
        }
    }
}

/// `k2 app sdk add` (0.46.6): list `sdk/server/dist` (the committed JS +
/// .d.ts that `scripts/sdk-server-dist.mjs` builds) as `SDK_SERVER_DIST`
/// with `include_str!`, so the daemon carries @k2/server's files and packs
/// them at its own version (`app_sdk::k2_server`). No node at build time.
fn sdk_server_dist(manifest: &std::path::Path) {
    let dist = manifest.join("../../sdk/server/dist");
    println!("cargo:rerun-if-changed={}", dist.display());
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    walk(&dist, &dist, &mut files);
    files.sort();
    assert!(
        files.iter().any(|(rel, _)| rel == "server/src/index.js"),
        "{} has no server/src/index.js: run `node scripts/sdk-server-dist.mjs`",
        dist.display()
    );
    let mut out = String::from(
        "/// Every file of `sdk/server/dist` but `SOURCES`, sorted: `(path under dist, text)`.\n\
         /// Generated by `build.rs`.\n\
         pub const SDK_SERVER_DIST: &[(&str, &str)] = &[\n",
    );
    for (rel, path) in &files {
        if rel == "SOURCES" {
            continue;
        }
        let path = path.to_str().expect("dist paths are UTF-8");
        writeln!(out, "    ({rel:?}, include_str!({path:?})),").expect("write to String");
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("sdk_server_dist.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}

fn walk(dir: &std::path::Path, base: &std::path::Path, acc: &mut Vec<(String, PathBuf)>) {
    for e in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}; run `node scripts/sdk-server-dist.mjs`", dir.display())) {
        let p = e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path();
        if p.is_dir() {
            println!("cargo:rerun-if-changed={}", p.display());
            walk(&p, base, acc);
        } else {
            let rel = p.strip_prefix(base).expect("under dist").components().map(|c| c.as_os_str().to_str().expect("UTF-8")).collect::<Vec<_>>().join("/");
            acc.push((rel, p));
        }
    }
}
