//! The App transport of the verb catalog (`prd-k2-app-runtime-v1` S23;
//! room-scope R1, R5, R6).
//!
//! Rows exposed to `app` describe the live `/cli/*` routes and sockets an
//! App reaches: one row per `(method, route)` pair and one per socket,
//! with closed schemas of the live wire. Banned field names are renamed
//! (`responseNames`: `relPath` ← `path`, room-scope RS7) and the server
//! SDK renames them back and drops every field the schema doesn't name.
//!
//! Generated from these rows by contract-gen (never edited by hand):
//! - [`APP_SURFACE_RS`], the route table the browser helper and every
//!   App's gateway link read (default deny: a route without a row is
//!   refused at both doors before any handler runs);
//! - [`SDK_VERBS_TS`], the server SDK's verb table and types;
//! - the `k2 study app-api` page (a fenced block in `cli/k2`).
//!
//! The lint rules for app rows are here ([`lint_row`], [`lint_catalog`]);
//! `contract::lint` calls them.

