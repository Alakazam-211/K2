//! `contract-gen`: every file K2 generates from the verb catalog
//! (prd-zen-user-widgets-v2 UWA4, UWA5, UWA9, UWA11, UWB28).
//!
//! Outputs, all rendered in memory by [`render`]:
//! - `src/renderer/lib/zen/zen-verbs.generated.ts`: `ZEN_VERBS` (every row
//!   with a `builtin` or `registered` renderer binding, verb → cap) and
//!   `ZEN_CUSTOM_VERBS` (rows exposed to `widget`).
//! - `src/renderer/lib/k2-caps.generated.ts`: the shared cap table.
//! - `sdk/generated/k2.d.ts`: types for the frame's `k2` object.
//! - `sdk/generated/k2-frame.js`: the widget verb table joined with the
//!   shared runtime `sdk/k2-runtime.js` into one classic script.
//! - `sdk/generated/contract-snapshot.json`: sha256 of the catalog, the
//!   runtime and every output, for the vitest twin of the freshness test.
//! - The fenced `k2 zen guide api` block in `cli/k2`.
//!
//! The bin (`cargo run -p k2-core --bin contract-gen`) writes them; the
//! freshness test below renders them again and fails on any difference. It
//! never rewrites a file itself. Nobody edits an output by hand.

