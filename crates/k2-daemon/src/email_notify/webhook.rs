    #[derive(Default)]
    struct FakeHooks {
        objs: std::sync::Mutex<Vec<J>>,
        writes: std::sync::Mutex<Vec<String>>,
        reload_fails: bool,
    }

    impl HookApi for FakeHooks {
        fn list(&self) -> Result<Vec<J>, String> {
            Ok(self.objs.lock().unwrap().clone())
        }
        fn put(&self, id: Option<&str>, mut body: J) -> Result<String, String> {
            let mut o = self.objs.lock().unwrap();
            // The mail server never shows the key back.
            body["signatureKey"] = json!({ "@type": "Value" });
            match id {
                Some(id) => {
                    self.writes.lock().unwrap().push(format!("update {id}"));
                    body["id"] = json!(id);
                    let slot = o.iter_mut().find(|x| x["id"] == json!(id)).expect("exists");
                    *slot = body;
                    Ok(id.to_string())
                }
                None => {
                    let id = format!("w{}", o.len() + 10);
                    self.writes.lock().unwrap().push(format!("create {id}"));
                    body["id"] = json!(id);
                    o.push(body);
                    Ok(id)
                }
            }
        }
        fn destroy(&self, id: &str) -> Result<(), String> {
            self.writes.lock().unwrap().push(format!("destroy {id}"));
            self.objs.lock().unwrap().retain(|x| x["id"] != json!(id));
            Ok(())
        }
        fn reload(&self) -> Result<(), String> {
            self.writes.lock().unwrap().push("reload".into());
            if self.reload_fails {
                Err("refused".into())
            } else {
                Ok(())
            }
        }
    }

    #[test]
    fn the_webhook_is_written_once_and_again_only_when_the_port_or_key_moves() {
        let api = FakeHooks::default();
        // Someone else's webhook is never touched.
        api.objs.lock().unwrap().push(json!({"id": "other", "url": "https://hooks.example.test/x", "enable": true}));
        assert_eq!(reconcile(&api, Some((4100, "key-a"))), Reconciled::Created);
        assert_eq!(*api.writes.lock().unwrap(), vec!["create w11", "reload"]);
        let ours = api.objs.lock().unwrap().iter().find(|o| is_ours(o)).cloned().expect("ours");
        assert_eq!(ours["url"], "http://127.0.0.1:4100/cli/email/events");
        assert_eq!(ours["eventsPolicy"], "include");
        assert_eq!(ours["events"].as_object().expect("map").len(), EVENTS.len());
        assert_eq!(ours["httpHeaders"][KEY_ID_HEADER], json!(key_id("key-a")));
        assert!(!ours.to_string().contains("key-a"), "the key itself isn't readable back");
        let d = desired(4100, "key-a");
        assert_eq!(d["signatureKey"], json!({"@type": "Value", "secret": "key-a"}));
        // Again: nothing to write.
        api.writes.lock().unwrap().clear();
        assert_eq!(reconcile(&api, Some((4100, "key-a"))), Reconciled::Unchanged);
        assert!(api.writes.lock().unwrap().is_empty(), "idempotent");
        // The daemon's port moved; then the key changed.
        assert_eq!(reconcile(&api, Some((4200, "key-a"))), Reconciled::Updated);
        assert_eq!(reconcile(&api, Some((4200, "key-b"))), Reconciled::Updated);
        assert_eq!(*api.writes.lock().unwrap(), vec!["update w11", "reload", "update w11", "reload"]);
        // A duplicate of ours (an older K2) goes; the box switch off removes ours only.
        api.objs.lock().unwrap().push(json!({"id": "w99", "url": "http://127.0.0.1:9/cli/email/events"}));
        api.writes.lock().unwrap().clear();
        assert_eq!(reconcile(&api, Some((4200, "key-b"))), Reconciled::Unchanged);
        assert_eq!(*api.writes.lock().unwrap(), vec!["destroy w99", "reload"]);
        assert_eq!(reconcile(&api, None), Reconciled::Removed(1));
        let left: Vec<J> = api.objs.lock().unwrap().clone();
        assert_eq!(left.len(), 1);
        assert_eq!(left[0]["id"], "other");
        assert_eq!(reconcile(&api, None), Reconciled::Removed(0));
        // A refused reload is reported (the object is saved; it applies at the next start).
        let api = FakeHooks { reload_fails: true, ..Default::default() };
        assert_eq!(reconcile(&api, Some((1, "k"))), Reconciled::NotLoaded("refused".into()));
    }

