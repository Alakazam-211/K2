#!/usr/bin/env python3
"""Live probe: K2's outside-forward Sieve on a real (throwaway) Stalwart.

prd-hostmail-external-forwarding-v1 §3.4 / §5. Runs the EXACT bytes K2's
composer writes (tests/mail/forward-goldens/*.sieve, pinned by the
sieve_user golden tests) on a loopback Stalwart started by
tests/mail/stalwart-sandbox-forward-gap.sh. The "outside" destination is a
loopback SMTP sink this script runs: an `x:MtaRoute` relay sends every
`outside.test` recipient there, so no mail ever leaves the machine.

  X1  every golden compiles (SieveScript/validate, then set as K2's
      service account writes it)
  X2  a plain inbound message is forwarded: the sink gets it, MAIL FROM is
      the forwarding mailbox (the forwarder return path, FW-A1), and the
      copy carries `X-K2-Forwarded: <host>`; the mailbox keeps its copy
  X3  a bounce (empty MAIL FROM) stays home (FW-A25)
  X4  a message already carrying this box's marker stays home (loop stop)
  X5  a message this box's Authentication-Results marks dmarc=fail stays
      home (the header is forged here; the test can only stop a forward)
  X6  spam stays home (GTUBE; recorded as INFO when this Stalwart doesn't
      score GTUBE as spam)
  X7  keep off: forwarded and NOT kept
  X8  a mailbox login (K2's Sieve lock) still can't SieveScript/set
  X9  K2's two forward throttles (x:MtaOutboundThrottle, source ==
      'autogenerated', keyed by sender and by localIp) are accepted

Every message has its own Message-ID (Stalwart also drops duplicates by
Message-ID, FW-A27, so a shared id would pass for the wrong reason).

    STALWART_PROBE_ADMIN='admin@example.test:<secret>' \\
      python3 -I tests/mail/stalwart-forward-external-probe.py --url http://127.0.0.1:18080 --smtp-port 20025

Run it only against a disposable Stalwart:
    STALWART_PROBE=stalwart-forward-external-probe.py tests/mail/stalwart-sandbox-forward-gap.sh 0.16.25
"""

