#!/usr/bin/env node
// Writes src/renderer/lib/shiki-allowlist.generated.ts: the shiki grammar and
// theme ids the code viewer may bundle, each with its fine-grained
// `shiki/langs/<id>.mjs` / `shiki/themes/<id>.mjs` loader.
//
// The set is every id in the installed shiki's bundledLanguagesInfo and
// bundledThemesInfo, minus every id in the left-out list (the file named by
// SHIKI_EXCLUDED_FILE in src/renderer/lib/shiki-vite-plugin.ts). Aliases come
// from bundledLanguagesInfo, kept only when they point at a kept grammar.
//
// Rerun after a shiki upgrade or a change to the left-out list:
//   node scripts/gen-shiki-allowlist.mjs
// src/renderer/lib/shiki-allowlist.test.ts fails while the generated file and
// the list disagree.

import { readFileSync, writeFileSync } from 'fs'
import { createRequire } from 'module'
import { dirname, resolve } from 'path'
import { fileURLToPath, pathToFileURL } from 'url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(resolve(root, 'package.json'))

const pluginSrc = readFileSync(resolve(root, 'src/renderer/lib/shiki-vite-plugin.ts'), 'utf8')
const fileMatch = /export const SHIKI_EXCLUDED_FILE = '([^']+)'/.exec(pluginSrc)
if (!fileMatch) throw new Error('SHIKI_EXCLUDED_FILE not found in shiki-vite-plugin.ts')
const excludedPath = resolve(root, fileMatch[1])

const excluded = { lang: new Set(), theme: new Set() }
for (const raw of readFileSync(excludedPath, 'utf8').split('\n')) {
  const line = raw.trim()
  if (!line || line.startsWith('#')) continue
  const m = /^shiki (lang|theme) ([A-Za-z0-9][A-Za-z0-9._+#-]*):/.exec(line)
  if (!m) throw new Error(`unreadable line in ${fileMatch[1]}: ${line}`)
  excluded[m[1]].add(m[2])
}

const shikiPkg = require.resolve('shiki/package.json')
const shikiVersion = JSON.parse(readFileSync(shikiPkg, 'utf8')).version
const { bundledLanguagesInfo } = await import(pathToFileURL(resolve(dirname(shikiPkg), 'dist/langs.mjs')).href)
const { bundledThemesInfo } = await import(pathToFileURL(resolve(dirname(shikiPkg), 'dist/themes.mjs')).href)

const allLangs = bundledLanguagesInfo.map((l) => l.id)
const allThemes = bundledThemesInfo.map((t) => t.id)
for (const id of excluded.lang) if (!allLangs.includes(id)) throw new Error(`left-out grammar ${id} is not in shiki ${shikiVersion}`)
for (const id of excluded.theme) if (!allThemes.includes(id)) throw new Error(`left-out theme ${id} is not in shiki ${shikiVersion}`)

const langs = bundledLanguagesInfo.filter((l) => !excluded.lang.has(l.id))
const themes = bundledThemesInfo.filter((t) => !excluded.theme.has(t.id))
const aliases = []
for (const l of langs) for (const a of l.aliases ?? []) if (!excluded.lang.has(a)) aliases.push([a, l.id])

const q = (s) => `'${s}'`
const out = `// GENERATED by scripts/gen-shiki-allowlist.mjs. Do not edit by hand.
//
// The shiki grammars and themes the code viewer may bundle: every id in
// shiki ${shikiVersion}'s bundledLanguagesInfo / bundledThemesInfo minus every id in
// ${fileMatch[1]} (${excluded.lang.size} grammars, ${excluded.theme.size} theme${excluded.theme.size === 1 ? '' : 's'} left out).
// Kept: ${langs.length} of ${allLangs.length} grammars, ${themes.length} of ${allThemes.length} themes.
// Regenerate with \`node scripts/gen-shiki-allowlist.mjs\` after a shiki upgrade
// or a change to the left-out list. Only shiki-allowlist.ts imports this.

import type { LanguageRegistration, ThemeRegistration } from 'shiki/core'

export type ShikiLangLoader = () => Promise<{ default: LanguageRegistration[] }>
export type ShikiThemeLoader = () => Promise<{ default: ThemeRegistration }>

export const GENERATED_LANG_LOADERS: Readonly<Record<string, ShikiLangLoader>> = {
${langs.map((l) => `  ${q(l.id)}: () => import(${q(`shiki/langs/${l.id}.mjs`)}),`).join('\n')}
}

export const GENERATED_THEME_LOADERS: Readonly<Record<string, ShikiThemeLoader>> = {
${themes.map((t) => `  ${q(t.id)}: () => import(${q(`shiki/themes/${t.id}.mjs`)}),`).join('\n')}
}

/** Alias -> grammar id, for kept grammars only. */
export const GENERATED_LANG_ALIASES: Readonly<Record<string, string>> = {
${aliases.map(([a, id]) => `  ${q(a)}: ${q(id)},`).join('\n')}
}
`
const target = resolve(root, 'src/renderer/lib/shiki-allowlist.generated.ts')
writeFileSync(target, out)
console.log(`wrote ${target}: ${langs.length} grammars, ${themes.length} themes, ${aliases.length} aliases`)
