//! Build script for `k2-core`.
//!
//! Its only job: list the Garden catalog (`src/zen/garden-catalog/*.toml`,
//! prd-zen-user-widgets-v2 R5) as `GARDEN_CATALOG_SOURCES`, so adding a
//! ready-made Garden is a data file with no Rust edit. See
//! `src/zen/garden_catalog.rs`.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = manifest.join("src/zen/garden-catalog");
    println!("cargo:rerun-if-changed=build.rs");
    // A directory path makes cargo rerun on any change inside it (add,
    // remove, edit).
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut files: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path())
        .filter(|p| p.extension().is_some_and(|x| x == "toml"))
        .map(|p| {
            let name = p.file_name().and_then(|n| n.to_str()).expect("catalog file names are UTF-8").to_string();
            (name, p)
        })
        .collect();
    files.sort();

    let mut out = String::from(
        "/// Every `src/zen/garden-catalog/*.toml`, sorted by file name: `(file, TOML)`.\n\
         /// Generated by `build.rs`.\n\
         pub const GARDEN_CATALOG_SOURCES: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &files {
        let path = path.to_str().expect("catalog paths are UTF-8");
        writeln!(out, "    ({name:?}, include_str!({path:?})),").expect("write to String");
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("zen_garden_catalog.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));

    sdk_server_dist(&manifest);
    agent_templates(&manifest);
}

/// Built-in agent templates (prd-agent-templates-v1 §2.2): every folder of
/// `agent-templates/` but `_*` is one template, embedded file by file as
/// `AGENT_TEMPLATE_SOURCES: &[(id, &[(path in the folder, text)])]`. The
/// shared "Working with your person and the team" block is
/// `AGENT_TEMPLATE_SHARED_BLOCK`. The loader validates every file (its
/// paths, its TOML, its placeholders) at runtime and in a test; this only
/// refuses a symlink, which a template may never hold (AT4).
fn agent_templates(manifest: &std::path::Path) {
    let dir = manifest.join("agent-templates");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut ids: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path())
        .filter(|p| p.is_dir())
        .map(|p| (p.file_name().and_then(|n| n.to_str()).expect("template folder names are UTF-8").to_string(), p))
        .filter(|(n, _)| !n.starts_with('_'))
        .collect();
    ids.sort();
    let mut out = String::from(
        "/// Every built-in agent template: `(id, [(path in its folder, text)])`,\n\
         /// sorted. Generated by `build.rs` from `agent-templates/`.\n\
         pub const AGENT_TEMPLATE_SOURCES: &[(&str, &[(&str, &str)])] = &[\n",
    );
    for (id, path) in &ids {
        let mut files = Vec::new();
        walk_no_links(path, path, &mut files);
        files.sort();
        writeln!(out, "    ({id:?}, &[").expect("write to String");
        for (rel, file) in &files {
            let file = file.to_str().expect("template paths are UTF-8");
            writeln!(out, "        ({rel:?}, include_str!({file:?})),").expect("write to String");
        }
        out.push_str("    ]),\n");
    }
    out.push_str("];\n");
    let shared = dir.join("_shared/working-with-your-person.md");
    assert!(shared.is_file(), "{} is missing", shared.display());
    writeln!(
        out,
        "/// The shared block `shared_block = true` appends. Generated by `build.rs`.\npub const AGENT_TEMPLATE_SHARED_BLOCK: &str = include_str!({:?});",
        shared.to_str().expect("UTF-8")
    )
    .expect("write to String");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("agent_templates.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}

fn walk_no_links(dir: &std::path::Path, base: &std::path::Path, acc: &mut Vec<(String, PathBuf)>) {
    for e in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())) {
        let p = e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path();
        let meta = std::fs::symlink_metadata(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()));
        assert!(!meta.file_type().is_symlink(), "{}: an agent template may not hold a symlink", p.display());
        if meta.is_dir() {
            println!("cargo:rerun-if-changed={}", p.display());
            walk_no_links(&p, base, acc);
        } else {
            let rel = p.strip_prefix(base).expect("under the template").components().map(|c| c.as_os_str().to_str().expect("UTF-8")).collect::<Vec<_>>().join("/");
            acc.push((rel, p));
        }
    }
}

/// `k2 app sdk add` (0.46.6): list `sdk/server/dist` (the committed JS +
/// .d.ts that `scripts/sdk-server-dist.mjs` builds) as `SDK_SERVER_DIST`
/// with `include_str!`, so the daemon carries @k2/server's files and packs
/// them at its own version (`app_sdk::k2_server`). No node at build time.
fn sdk_server_dist(manifest: &std::path::Path) {
    let dist = manifest.join("../../sdk/server/dist");
    println!("cargo:rerun-if-changed={}", dist.display());
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    walk(&dist, &dist, &mut files);
    files.sort();
    assert!(
        files.iter().any(|(rel, _)| rel == "server/src/index.js"),
        "{} has no server/src/index.js: run `node scripts/sdk-server-dist.mjs`",
        dist.display()
    );
    let mut out = String::from(
        "/// Every file of `sdk/server/dist` but `SOURCES`, sorted: `(path under dist, text)`.\n\
         /// Generated by `build.rs`.\n\
         pub const SDK_SERVER_DIST: &[(&str, &str)] = &[\n",
    );
    for (rel, path) in &files {
        if rel == "SOURCES" {
            continue;
        }
        let path = path.to_str().expect("dist paths are UTF-8");
        writeln!(out, "    ({rel:?}, include_str!({path:?})),").expect("write to String");
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("sdk_server_dist.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}

fn walk(dir: &std::path::Path, base: &std::path::Path, acc: &mut Vec<(String, PathBuf)>) {
    for e in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}; run `node scripts/sdk-server-dist.mjs`", dir.display())) {
        let p = e.unwrap_or_else(|e| panic!("{}: {e}", dir.display())).path();
        if p.is_dir() {
            println!("cargo:rerun-if-changed={}", p.display());
            walk(&p, base, acc);
        } else {
            let rel = p.strip_prefix(base).expect("under dist").components().map(|c| c.as_os_str().to_str().expect("UTF-8")).collect::<Vec<_>>().join("/");
            acc.push((rel, p));
        }
    }
}
