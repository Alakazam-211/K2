-- Thread push message previews (0.46.1, Rosson 2026-10-17): each phone
-- chooses whether its lock screen shows the start of an agent's message
-- (`POST /cli/push/register-device` `previews`).
--
-- Nullable on purpose: NULL = the phone never said, which reads as ON
-- (Rosson asked for previews). Every device registered before this
-- migration therefore keeps getting pushes, now with previews, until it
-- sends `previews: false`. 1 = on, 0 = off. The owner's server-wide
-- `pushMessagePreviews` app setting still overrides it (off = no device
-- gets a preview).
--
-- PRIVACY: a preview is message text; it passes through K2's push relay
-- and Apple (APNs) or Google (FCM). A secret card never carries one.
ALTER TABLE push_devices ADD COLUMN previews INTEGER;
