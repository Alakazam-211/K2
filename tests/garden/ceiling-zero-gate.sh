#!/usr/bin/env bash
# Tests for scripts/brand/ceiling-zero-gate.sh on scratch repos: a ceiling
# of 0 in every class passes, any row or any class above 0 (P too) is
# refused, as is a missing tag, a missing or malformed file. Run-time rows
# (class R) are listed and not counted for our default brand or a brand
# with cli.no_bash = false, and refused for a brand with no shell CLI
# (brand/xy, or a brand file that leaves no_bash out). Today's tree is not
# asserted either way: the gate's answer on it moves as families turn
# native. No CLI, no daemon, no cargo.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/../.." && pwd)"
G="$HERE/scripts/brand/ceiling-zero-gate.sh"
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
pass=0
ok() { pass=$((pass + 1)); }
die() { echo "FAIL: $*" >&2; exit 1; }
F="crates/k5-cli/tests/data/native_bar_ceiling.tsv"
HEAD3='# GENERATED by crates/k5-cli/tests/native_bar.rs (NATIVE_BAR_WRITE=<file>): the probes
# k5 still hands to bash. It may only fall; the ship bar is no row of a counted class (V verb,
# H help, F flag, E edge; P listed, not counted; R run-time: counted for a no-bash brand).'

R="$T/repo"
mkdir -p "$R/$(dirname "$F")"
git -C "$R" init -q
git -C "$R" config user.email t@example.invalid
git -C "$R" config user.name t
# ceiling <summary counts> [rows...]: write the file in the repo.
ceiling() {
    local s="$1"; shift
    { printf '%s\n' "$HEAD3" "# $s"; printf 'class\tfamily\tform\n'; if [ $# -gt 0 ]; then printf '%s\n' "$@"; fi; } > "$R/$F"
}
tag() { git -C "$R" add -A && git -C "$R" commit -qm "$1" && git -C "$R" tag "$1"; }
gate() { rc=0; out="$(bash "$G" "$@" 2>&1)" || rc=$?; }

ceiling "0 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 0, R 0"
tag v-zero
ceiling "28 of 5117 probes fall through: V 0, H 28, F 0, E 0, P 0, R 0" "$(printf 'H\tmail\tmail status --help')"
tag v-help
ceiling "1 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 1, R 0" "$(printf 'P\tdb\tdb list')"
tag v-p
ceiling "0 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 0, R 0" "$(printf 'V\tdb\tdb list')"
tag v-row
ceiling "0 of 5117 probes fall through: V 1, H 0, F 0, E 0, P 0, R 0"
tag v-count
printf 'class\tfamily\tform\n' > "$R/$F"
tag v-nosum
ceiling "0 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 0, R 0"
sed -i.bak '/^class/d' "$R/$F" && rm -f "$R/$F.bak"
tag v-nohead
ceiling "0 of 0 probes fall through: V 0, H 0, F 0, E 0, P 0, R 0"
tag v-none
ceiling "2 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 0, R 2" \
    "$(printf 'R\ttalk\ttalk <ws>@<host> [proxy-socks5]')" "$(printf 'R\tdoc\tdoc list [locale-lc-all-latin1]')"
tag v-r
ceiling "0 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 0, R 1"
tag v-rcount
ceiling "0 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 0, R 0" "$(printf 'R\tdoc\tdoc list [tty]')"
tag v-rrow
ceiling "1 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 1, R 0" "$(printf 'P\tdb\tdb list')"
tag v-p2
# A long ceiling (the real one has thousands of R rows): a reader that
# stops early must not kill the gate (SIGPIPE under pipefail).
ceiling "5000 of 70000 probes fall through: V 0, H 0, F 0, E 0, P 0, R 5000" \
    "$(for i in $(seq 1 5000); do printf 'R\tdoc\tdoc list x%s [tty]\n' "$i"; done)"
tag v-long
ceiling "0 of 5117 probes fall through: V 0, H 0, F 0, E 0, P 0"
tag v-old
git -C "$R" rm -q "$F" && git -C "$R" commit -qm gone && git -C "$R" tag v-gone

gate --tag v-zero "$R"
[ "$rc" = 0 ] || die "v-zero: $out"; ok
case "$out" in *"tag v-zero: 0 of 5117 probes fall through (V 0, H 0, F 0, E 0, P 0, R 0); build it"*) ok ;; *) die "v-zero: $out" ;; esac
for t in v-help v-p v-row v-count; do
    gate --tag "$t" "$R"
    [ "$rc" = 1 ] || die "$t passed: $out"; ok
    case "$out" in *"REFUSED (tag $t): every command line must be native"*) ok ;; *) die "$t: $out" ;; esac
done
case "$(bash "$G" --tag v-help "$R" 2>&1 || true)" in *"mail status --help"*) ok ;; *) die "the refusal names no row" ;; esac
gate --tag v-nosum "$R"; [ "$rc" = 1 ] && [[ "$out" == *"no single summary line"* ]] || die "v-nosum: $out"; ok
gate --tag v-nohead "$R"; [ "$rc" = 1 ] && [[ "$out" == *"header is not class, family, form"* ]] || die "v-nohead: $out"; ok
gate --tag v-none "$R"; [ "$rc" = 1 ] && [[ "$out" == *"names no probes"* ]] || die "v-none: $out"; ok
gate --tag v-old "$R"; [ "$rc" = 1 ] && [[ "$out" == *"summary line is not the native bar's"* ]] || die "v-old (no R): $out"; ok

# Run-time rows (R): listed, not counted, for our default brand and a brand
# with the shell CLI; refused, by row, for a brand with none.
B="$T/brands"
mkdir -p "$B/left-out" "$B/bad" "$B/no-id"
sed '/^no_bash = /d' "$HERE/brand/xy/brand.toml" > "$B/left-out/brand.toml"
sed 's/^no_bash = true/no_bash = "yes"/' "$HERE/brand/xy/brand.toml" > "$B/bad/brand.toml"
sed '/^id = /d' "$HERE/brand/xy/brand.toml" > "$B/no-id/brand.toml"
printf 'id = "xy"\n[cli\n' > "$B/broken.toml"
grep -q '^no_bash = true$' "$HERE/brand/xy/brand.toml" || die "brand/xy is no longer a no-bash brand"
grep -q '^no_bash = false$' "$HERE/brand/k2/brand.toml" || die "brand/k2 no longer carries the shell CLI"
for t in v-r v-rcount v-rrow; do
    for b in "" "$HERE/brand/k2" "$HERE/brand/k5/brand.toml"; do
        if [ -z "$b" ]; then gate --tag "$t" "$R"; else gate --brand "$b" --tag "$t" "$R"; fi
        [ "$rc" = 0 ] && [[ "$out" == *"R "?" run-time hand-off(s) listed, not counted for "*"build it"* ]] \
            || die "$t ${b:-(no brand)}: R must not count: $out"; ok
    done
    for b in "$HERE/brand/xy" "$B/left-out"; do
        gate --brand "$b" --tag "$t" "$R"
        [ "$rc" = 1 ] && [[ "$out" == *"xy has no shell CLI (cli.no_bash)"* ]] \
            && [[ "$out" == *"REFUSED (tag $t): every command line must be native in every environment"* ]] \
            || die "$t --brand $b: R must count: $out"; ok
    done
done
gate --tag v-long "$R"; [ "$rc" = 0 ] && [[ "$out" == *"R 5000 run-time hand-off(s) listed, not counted"* ]] || die "v-long, default: rc $rc: $out"; ok
gate --brand "$HERE/brand/xy" --tag v-long "$R"
[ "$rc" = 1 ] && [[ "$out" == *"R 5000 run-time hand-off(s) would each be refused"* ]] && [[ "$out" == *"doc list x20 [tty]"* ]] \
    && [[ "$out" != *"doc list x21 [tty]"* ]] || die "v-long, xy: rc $rc: $out"; ok
case "$(bash "$G" --brand "$HERE/brand/xy" --tag v-r "$R" 2>&1 || true)" in
    *"talk <ws>@<host> [proxy-socks5]"*"doc list [locale-lc-all-latin1]"*) ok ;; *) die "the R refusal names no row" ;; esac
gate --brand "$HERE/brand/xy" --tag v-zero "$R"
[ "$rc" = 0 ] && [[ "$out" == *"0 of 5117 probes fall through (V 0, H 0, F 0, E 0, P 0, R 0) for xy, which has no shell CLI; build it"* ]] \
    || die "v-zero, xy: $out"; ok
for t in v-help v-p v-p2 v-row v-count; do
    for b in "$HERE/brand/k2" "$HERE/brand/xy"; do
        gate --brand "$b" --tag "$t" "$R"
        [ "$rc" = 1 ] && [[ "$out" == *"REFUSED (tag $t): every command line must be native before"* ]] || die "$t --brand $b: $out"; ok
    done
done
gate --brand "$B/nowhere" --tag v-zero "$R"; [ "$rc" = 1 ] && [[ "$out" == *"no brand file at $B/nowhere"* ]] || die "no brand file: $out"; ok
for f in "$B/bad" "$B/no-id" "$B/broken.toml"; do
    gate --brand "$f" --tag v-zero "$R"; [ "$rc" = 1 ] && [[ "$out" == *"REFUSED (tag v-zero): the brand file "* ]] || die "brand $f: $out"; ok
done
gate --tag v-gone "$R"; [ "$rc" = 1 ] && [[ "$out" == *"the tag has no $F"* ]] || die "v-gone: $out"; ok
gate --tag v-nope "$R"; [ "$rc" = 1 ] && [[ "$out" == *"no tag named v-nope"* ]] || die "v-nope: $out"; ok
# A branch of that name is not a tag.
git -C "$R" branch -q b-zero v-zero
gate --tag b-zero "$R"; [ "$rc" = 1 ] && [[ "$out" == *"no tag named b-zero"* ]] || die "a branch: $out"; ok

# --tree reads the checked-out file.
git -C "$R" checkout -q v-zero
gate --tree "$R"; [ "$rc" = 0 ] && [[ "$out" == *"the working tree: 0 of 5117"* ]] || die "--tree v-zero: $out"; ok
git -C "$R" checkout -q v-help
gate --tree "$R"; [ "$rc" = 1 ] || die "--tree v-help passed: $out"; ok
rm "$R/$F"
gate --tree "$R"; [ "$rc" = 1 ] && [[ "$out" == *"no $F"* ]] || die "--tree, no file: $out"; ok

# Usage errors.
for args in "" "--nope" "--tag" "--tree a b" "--brand" "--tree --brand"; do
    # shellcheck disable=SC2086
    gate $args
    [ "$rc" = 2 ] && [[ "$out" == usage:* ]] || die "args '$args': rc $rc: $out"; ok
done

# The real file has the shape the gate reads (whatever its counts), for
# our brand and for a no-bash one.
gate --tree "$HERE"
case "$out" in *"build it"*|*"every command line must be native"*) ok ;; *) die "the real ceiling: $out" ;; esac
gate --brand "$HERE/brand/xy" --tree "$HERE"
case "$out" in *"build it"*|*"every command line must be native"*) ok ;; *) die "the real ceiling, xy: $out" ;; esac

echo "ceiling-zero gate tests: $pass passed"
