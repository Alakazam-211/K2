/// A schema reduced to what the SDK projects with (no titles or
/// descriptions), written with sorted keys.
fn projection_schema(s: &J) -> J {
    match s {
        J::Object(o) => {
            let mut m = serde_json::Map::new();
            for (k, v) in o {
                if matches!(k.as_str(), "title" | "description" | "default" | "minimum" | "maximum" | "minLength" | "maxLength" | "required") {
                    continue;
                }
                let v = if k == "properties" {
                    match v {
                        J::Object(p) => J::Object(p.iter().map(|(pk, pv)| (pk.clone(), projection_schema(pv))).collect()),
                        other => other.clone(),
                    }
                } else {
                    projection_schema(v)
                };
                m.insert(k.clone(), v);
            }
            J::Object(m)
        }
        J::Array(a) => J::Array(a.iter().map(projection_schema).collect()),
        other => other.clone(),
    }
}

/// JSON with object keys in byte order, whatever map serde_json keeps.
fn canon(v: &J) -> String {
    match v {
        J::Object(o) => {
            let parts: Vec<String> = sorted_keys(o).iter().map(|k| format!("{}:{}", J::String(k.clone()), canon(&o[k.as_str()]))).collect();
            format!("{{{}}}", parts.join(","))
        }
        J::Array(a) => format!("[{}]", a.iter().map(canon).collect::<Vec<_>>().join(",")),
        other => other.to_string(),
    }
}

fn ts_record(m: &std::collections::BTreeMap<String, String>) -> String {
    if m.is_empty() {
        return "{}".into();
    }
    let parts: Vec<String> = m.iter().map(|(k, v)| format!("{}: {}", ts_str(k), ts_str(v))).collect();
    format!("{{ {} }}", parts.join(", "))
}

fn sdk_doc(v: &VerbRow) -> String {
    let cap = v.cap.as_deref().map(|c| format!("cap {c}")).unwrap_or_else(|| "no cap".into());
    let wire = match (&v.bindings.http, &v.bindings.socket) {
        (Some(h), _) => format!("{} {}", if h.method == HttpMethod::Get { "GET" } else { "POST" }, h.route),
        (None, Some(s)) => format!("WS {}?{}=", s.path, s.param.as_deref().unwrap_or("")),
        _ => String::new(),
    };
    format!("  /** {} {cap} · {wire}. e.g. `{}` */\n", v.doc, v.example.replace("*/", "* /"))
}

