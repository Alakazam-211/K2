const BY_NAME: ReadonlyMap<string, GroupIconDef> = new Map(GROUP_ICONS.map((d) => [d.name, d]))

/** The icon for a stored name, or null (unknown or none: draw the dot). */
export function groupIcon(name: string | null | undefined): GroupIconDef | null {
  if (!name) return null
  return BY_NAME.get(name) ?? null
}

/** Icons whose name or keywords start with every word of `query`
 *  (case-insensitive). An empty query returns them all. */
export function searchGroupIcons(query: string): GroupIconDef[] {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean)
  if (words.length === 0) return [...GROUP_ICONS]
  return GROUP_ICONS.filter((d) => {
    const hay = [...d.name.split('-'), d.name, ...d.keywords]
    return words.every((w) => hay.some((h) => h.startsWith(w)))
  })
}
