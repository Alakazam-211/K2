/// The one argument an app row takes (an object), when it takes any.
pub const ARGS: &str = "args";

/// Rows exposed to `app`, in file order.
pub fn rows(c: &Catalog) -> Vec<&VerbRow> {
    c.verbs_exposed_to(Exposure::App)
}

/// One `(method, route)` an App-facing door forwards.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HttpPair<'a> {
    pub method: &'static str,
    pub route: &'a str,
    pub verb: &'a str,
    pub door: Option<Door>,
}

/// Every App-facing HTTP pair, in file order. A GET row also opens HEAD
/// unless it says `head: false`.
pub fn http_pairs(c: &Catalog) -> Vec<HttpPair<'_>> {
    let mut out = Vec::new();
    for v in rows(c) {
        let Some(h) = &v.bindings.http else { continue };
        let method = match h.method {
            HttpMethod::Get => "GET",
            HttpMethod::Post => "POST",
        };
        out.push(HttpPair { method, route: &h.route, verb: &v.verb, door: h.door });
        if h.method == HttpMethod::Get && h.head != Some(false) {
            out.push(HttpPair { method: "HEAD", route: &h.route, verb: &v.verb, door: h.door });
        }
    }
    out
}

/// Every App-facing socket: `(path, required query parameter, verb)`.
pub fn sockets(c: &Catalog) -> Vec<(&str, &str, &str)> {
    rows(c)
        .into_iter()
        .filter_map(|v| {
            let s = v.bindings.socket.as_ref()?;
            Some((s.path.as_str(), s.param.as_deref().unwrap_or(""), v.verb.as_str()))
        })
        .collect()
}

// ── lint ─────────────────────────────────────────────────────────────

fn props_of(s: &J) -> BTreeSet<&str> {
    s.get("properties").and_then(J::as_object).map(|p| p.keys().map(String::as_str).collect()).unwrap_or_default()
}

/// Every object key named anywhere in a schema.
fn field_names<'a>(s: &'a J, out: &mut BTreeSet<&'a str>) {
    let Some(o) = s.as_object() else { return };
    if let Some(props) = o.get("properties").and_then(J::as_object) {
        for (k, p) in props {
            out.insert(k.as_str());
            field_names(p, out);
        }
    }
    for key in ["items", "additionalProperties"] {
        if let Some(sub) = o.get(key) {
            field_names(sub, out);
        }
    }
}

/// Rules for one row (`contract::lint` calls this for every row).
pub(super) fn lint_row(v: &VerbRow, out: &mut Vec<String>) {
    let name = &v.verb;
    let app = v.exposed_to(Exposure::App);
    if let Some(h) = &v.bindings.http {
        if !app && (h.door.is_some() || !h.query.is_empty() || !h.response_names.is_empty() || h.head.is_some()) {
            out.push(format!("{name}: door, query, head and responseNames are for app rows"));
        }
        if h.head.is_some() && h.method != HttpMethod::Get {
            out.push(format!("{name}: head is for GET rows"));
        }
    }
    if let Some(s) = &v.bindings.socket {
        if !app && s.param.is_some() {
            out.push(format!("{name}: a socket param is for app rows"));
        }
    }
    if !app {
        return;
    }
    if v.reach != Reach::Portable {
        out.push(format!("{name}: an app row is reach portable"));
    }
    if v.bindings.renderer.is_some() {
        out.push(format!("{name}: an app row has no renderer binding (its transport is the live route)"));
    }
    // One reveal = both surfaces (room-scope §0.2, RS-A15): an app row may
    // also be `garden-local` (the Garden bridge, through this computer's
    // daemon at `/cli/zen/call`). The `widget` transport (the renderer's
    // bridge) stays separate until G1 joins those verb sets (Q29).
    if v.exposed_to(Exposure::Widget) {
        out.push(format!("{name}: an app row is exposed to app and garden-local, never widget, until G1 joins those verbs (Q29)"));
    }
    if v.exposed_to(Exposure::GardenLocal) && v.kind != VerbKind::Call {
        out.push(format!("{name}: an app + garden-local row is a call (the Garden door answers calls)"));
    }
    match v.kind {
        VerbKind::Call => {
            if v.bindings.http.is_none() || v.bindings.socket.is_some() {
                out.push(format!("{name}: an app call binds one http route and no socket"));
            }
        }
        VerbKind::Subscribe => {
            match &v.bindings.socket {
                Some(s) if s.param.as_deref().is_some_and(|p| !p.is_empty()) => {}
                _ => out.push(format!("{name}: an app subscribe binds a socket with its param (GA1)")),
            }
            if v.bindings.http.is_some() {
                out.push(format!("{name}: an app subscribe binds no http route"));
            }
        }
        VerbKind::Event => out.push(format!("{name}: an app row is a call or a subscribe")),
    }
    let items = request_items(v);
    let props: BTreeSet<&str> = match items.as_slice() {
        [] => BTreeSet::new(),
        [a] => {
            if a.get("title").and_then(J::as_str) != Some(ARGS) || a.get("type").and_then(J::as_str) != Some("object") {
                out.push(format!("{name}: an app row's one argument is `{ARGS}`, an object"));
            }
            if a.get("default").is_some() && !a.get("required").and_then(J::as_array).is_none_or(|r| r.is_empty()) {
                out.push(format!("{name}: optional args can't have required keys"));
            }
            props_of(a)
        }
        _ => {
            out.push(format!("{name}: an app row takes one argument, `{ARGS}` (an object)"));
            BTreeSet::new()
        }
    };
    if let Some(h) = &v.bindings.http {
        for k in h.params.keys() {
            if !props.contains(k.as_str()) {
                out.push(format!("{name}: params names '{k}', which isn't an args property"));
            }
        }
        if h.method == HttpMethod::Get && !h.query.is_empty() {
            out.push(format!("{name}: a GET sends every argument in the query; query is for POST rows"));
        }
        if v.effect == Effect::Read && h.method == HttpMethod::Post && v.kind == VerbKind::Call {
            // A read over POST is allowed (db.query reads), nothing to add.
        }
        for k in &h.query {
            if !props.contains(k.as_str()) {
                out.push(format!("{name}: query names '{k}', which isn't an args property"));
            }
        }
        let mut names = BTreeSet::new();
        field_names(&v.response, &mut names);
        for (k, wire) in &h.response_names {
            if !names.contains(k.as_str()) {
                out.push(format!("{name}: responseNames '{k}' isn't a response field"));
            }
            if k == wire {
                out.push(format!("{name}: responseNames '{k}' renames to itself"));
            }
        }
    }
    if let Some(s) = &v.bindings.socket {
        if let Some(p) = s.param.as_deref().filter(|p| !p.is_empty()) {
            if !props.contains(p) {
                out.push(format!("{name}: the socket param '{p}' isn't an args property"));
            }
        }
    }
}

/// Rules across rows: one row per `(method, route)` pair and per socket.
pub(super) fn lint_catalog(c: &Catalog, out: &mut Vec<String>) {
    let mut seen = BTreeSet::new();
    for p in http_pairs(c) {
        if !seen.insert((p.method, p.route)) {
            out.push(format!("{}: {} {} has two app rows", p.verb, p.method, p.route));
        }
    }
    let mut socks = BTreeSet::new();
    for (path, _, verb) in sockets(c) {
        if !socks.insert(path) {
            out.push(format!("{verb}: socket {path} has two app rows"));
        }
    }
}

