// ── registry ids ────────────────────────────────────────────────────

const ALPHABET: &[u8; 32] = b"abcdefghijklmnopqrstuvwxyz792013";

/// A Stalwart registry id for a queue id: Stalwart's own `Id::as_string`
/// (a Crockford-style base32, 4 bits then 5-bit groups, with its
/// alphabet). Probe P1's pair: `337364143281548288` ↔ `jluo27qealaa`.
pub fn registry_id(n: u64) -> String {
    if n == 0 {
        return "a".to_string();
    }
    const STOP: u64 = 1 << 60;
    let mut n = n;
    let mut out = String::with_capacity(13);
    match (n >> 60) as usize {
        0 => {
            n = (n << 4) | 1;
            n <<= n.leading_zeros() / 5 * 5;
        }
        top => {
            n = (n << 4) | 1;
            out.push(ALPHABET[top] as char);
        }
    }
    while n != STOP {
        out.push(ALPHABET[(n >> 59) as usize] as char);
        n <<= 5;
    }
    out
}

// ── the signature ───────────────────────────────────────────────────

/// HMAC-SHA256 (RFC 2104; a key over 64 bytes is hashed first).
pub fn hmac_sha256(key: &[u8], msg: &[u8]) -> [u8; 32] {
    let mut k = [0u8; 64];
    if key.len() > 64 {
        k[..32].copy_from_slice(&Sha256::digest(key));
    } else {
        k[..key.len()].copy_from_slice(key);
    }
    let mut inner = Sha256::new();
    inner.update(k.map(|b| b ^ 0x36));
    inner.update(msg);
    let ih = inner.finalize();
    let mut outer = Sha256::new();
    outer.update(k.map(|b| b ^ 0x5c));
    outer.update(ih);
    outer.finalize().into()
}

/// What Stalwart puts in `X-Signature`: standard base64 of the HMAC of the
/// body under the key's bytes.
pub fn sign(key: &str, body: &[u8]) -> String {
    use base64::Engine as _;
    base64::engine::general_purpose::STANDARD.encode(hmac_sha256(key.as_bytes(), body))
}

/// Does `got` (the header) sign `body` under `key`? Constant time.
pub fn signature_ok(key: &str, body: &[u8], got: Option<&str>) -> bool {
    use subtle::ConstantTimeEq;
    let Some(got) = got.map(str::trim).filter(|g| !g.is_empty()) else { return false };
    let want = sign(key, body);
    want.len() == got.len() && bool::from(want.as_bytes().ct_eq(got.as_bytes()))
}

/// The non-secret id of a key (16 hex of its SHA-256).
pub fn key_id(key: &str) -> String {
    Sha256::digest(key.as_bytes()).iter().take(8).map(|b| format!("{b:02x}")).collect()
}

/// One header's value from a request head (case-insensitive name).
pub fn header<'a>(head: &'a str, name: &str) -> Option<&'a str> {
    head.lines()
        .skip(1)
        .take_while(|l| !l.trim().is_empty())
        .filter_map(|l| l.split_once(':'))
        .find(|(k, _)| k.trim().eq_ignore_ascii_case(name))
        .map(|(_, v)| v.trim())
}

// ── the events ──────────────────────────────────────────────────────

/// One webhook event, the fields K2 reads.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HookEvent {
    pub kind: String,
    /// Decimal (a u64).
    pub queue_id: Option<String>,
    /// The return path (`<>` for a bounce).
    pub from: Option<String>,
    /// Lower case.
    pub to: Vec<String>,
    pub code: Option<u64>,
    /// The event's `details` when it is text (a `delivery.dsn-perm-fail`
    /// carries the failure there, enhanced status code included). Can name
    /// a recipient: never logged.
    pub details: Option<String>,
}

fn decimal(v: &J) -> Option<String> {
    match v {
        J::Number(n) => n.as_u64().map(|n| n.to_string()),
        J::String(s) => s.trim().parse::<u64>().ok().map(|n| n.to_string()),
        _ => None,
    }
}

fn addresses(v: Option<&J>) -> Vec<String> {
    let one = |x: &J| x.as_str().map(|s| s.trim().trim_matches(|c| c == '<' || c == '>').to_ascii_lowercase()).filter(|s| s.contains('@'));
    match v {
        Some(J::Array(a)) => a.iter().filter_map(one).collect(),
        Some(x) => one(x).into_iter().collect(),
        None => Vec::new(),
    }
}

/// `{events:[{id,createdAt,type,data}]}` → the events (an event that
/// isn't an object, or has no type, is skipped).
pub fn parse_events(body: &[u8]) -> Result<Vec<HookEvent>, String> {
    let v: J = serde_json::from_slice(body).map_err(|_| "the body isn't JSON".to_string())?;
    let list = v.get("events").and_then(J::as_array).ok_or_else(|| "the body has no events list".to_string())?;
    Ok(list
        .iter()
        .filter_map(|e| {
            let kind = e.get("type")?.as_str()?.to_string();
            let data = e.get("data").cloned().unwrap_or(J::Null);
            Some(HookEvent {
                kind,
                queue_id: data.get("queueId").and_then(decimal),
                from: data.get("from").and_then(J::as_str).map(|s| s.trim().trim_matches(|c| c == '<' || c == '>').to_ascii_lowercase()),
                to: addresses(data.get("to")),
                code: data.get("code").and_then(J::as_u64),
                details: data.get("details").and_then(J::as_str).map(str::to_string),
            })
        })
        .collect())
}

/// The outcome one event gives its recipients (`None`: none from here;
/// bounces come from delivery reports).
pub fn outcome_for(e: &HookEvent) -> Option<&'static str> {
    match e.kind.as_str() {
        "delivery.delivered" => Some(oc::K_DELIVERED),
        "delivery.dsn-temp-fail" | "delivery.rcpt-to-failed" => Some(oc::K_DELAYED),
        "delivery.rcpt-to-rejected" if e.code.is_some_and(|c| (400..500).contains(&c)) => Some(oc::K_DELAYED),
        _ => None,
    }
}

/// Waits before asking the queue again for a message it doesn't show yet.
/// Stalwart emits the queued event just before it writes the message to
/// the queue (`smtp/src/queue/spool.rs`, 0.16.25), so a first miss is
/// retried briefly. (In the live probes every miss was a message that had
/// already left the queue, which stays `submitted`; the retry costs about
/// 1.7 s on those.) Tests don't wait.
const QUEUE_RETRY_MS: &[u64] = if cfg!(test) { &[0, 0, 0] } else { &[200, 500, 1_000] };

/// The envelope id of a queued message, asked again after short waits
/// while the queue doesn't show it yet (`Ok(None)` after the last try).
pub fn lookup_queued(engine: &dyn super::engine::MailEngine, registry_id: &str) -> Result<Option<String>, String> {
    let mut found = engine.queued_env_id(registry_id)?;
    for ms in QUEUE_RETRY_MS {
        if found.is_some() {
            break;
        }
        std::thread::sleep(std::time::Duration::from_millis(*ms));
        found = engine.queued_env_id(registry_id)?;
    }
    Ok(found)
}

/// What one batch did.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Applied {
    /// New queue id → send pairs.
    pub linked: usize,
    /// Queued K2 messages that had already left the queue (no pair).
    pub missed: usize,
    /// Outcomes recorded.
    pub recorded: usize,
    /// Outside-forward outcomes recorded ([`crate::mail::forward_outcomes`]).
    pub forwards: usize,
}

/// Apply one batch (the db and, for a new K2 message, one queue lookup).
pub fn apply(events: &[HookEvent], now: i64) -> Applied {
    let mut out = Applied::default();
    if events.is_empty() {
        return out;
    }
    out.forwards = crate::mail::forward_outcomes::apply(events, now).recorded;
    if !super::box_enabled() {
        return out;
    }
    // K2's hosted senders by envelope account (the return path they submit with).
    let senders: Vec<Sender> = {
        let db = k2_core::db::shared();
        let conn = db.lock();
        store::list_senders(&conn, false).unwrap_or_default()
    };
    let by_envelope = |from: &str| -> Option<&Sender> {
        senders.iter().find(|s| s.path == store::PATH_HOSTED && s.envelope().eq_ignore_ascii_case(from))
    };
    let mut engine = None;
    for e in events {
        let Some(qid) = e.queue_id.as_deref() else { continue };
        if e.kind == QUEUED {
            let Some(s) = e.from.as_deref().and_then(by_envelope) else { continue };
            let known = {
                let db = k2_core::db::shared();
                let conn = db.lock();
                oc::log_for_queue(&conn, qid).ok().flatten().is_some()
            };
            if known {
                continue;
            }
            let Ok(n) = qid.parse::<u64>() else { continue };
            if engine.is_none() {
                match super::engine::mail_engine() {
                    Ok(x) => engine = Some(x),
                    Err(f) => {
                        k2_core::log_debug!("[email-notify] webhook: queue lookups skipped: {}", f.code);
                        return out;
                    }
                }
            }
            let Some(eng) = engine.as_ref() else { continue };
            let env = match lookup_queued(eng.as_ref(), &registry_id(n)) {
                Ok(v) => v,
                Err(_) => {
                    // E22: the queue id only, never the mail server's words
                    // (they can name a recipient).
                    k2_core::log_debug!("[email-notify] WARN webhook: queue lookup for {qid} failed");
                    continue;
                }
            };
            let db = k2_core::db::shared();
            let conn = db.lock();
            // Only this sender's own send: anything else is not K2's to keep.
            match env.and_then(|id| store::get_log(&conn, &id).ok().flatten()).filter(|r| r.sender_id == s.id) {
                Some(row) => {
                    if oc::link_queue(&conn, qid, &row.id, now).unwrap_or(false) {
                        out.linked += 1;
                    }
                }
                None => out.missed += 1,
            }
            continue;
        }
        let Some(kind) = outcome_for(e) else { continue };
        let db = k2_core::db::shared();
        let conn = db.lock();
        let Some(row) = oc::log_for_queue(&conn, qid).ok().flatten().and_then(|id| store::get_log(&conn, &id).ok().flatten()) else {
            continue;
        };
        for to in &e.to {
            if !row.to.iter().any(|t| t.trim().eq_ignore_ascii_case(to)) {
                continue;
            }
            let code = e.code.map(|c| c.to_string());
            match oc::record(&conn, &row.id, &row.sender_id, to, kind, code.as_deref(), oc::SRC_WEBHOOK, now) {
                Ok(true) => out.recorded += 1,
                Ok(false) => {}
                // E22: ids only.
                Err(_) => k2_core::log_debug!("[email-notify] WARN webhook: an outcome for log {} wasn't stored", row.id),
            }
        }
    }
    out
}

