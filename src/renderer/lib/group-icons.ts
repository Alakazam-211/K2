export interface GroupIconDef {
  /** The Lucide name, as stored and synced. */
  name: string
  Icon: LucideIcon
  /** Extra words the search matches (the name's own words always match). */
  keywords: readonly string[]
}

const def = (name: string, Icon: LucideIcon, keywords: string): GroupIconDef => ({
  name,
  Icon,
  keywords: keywords.split(' ').filter(Boolean),
})

