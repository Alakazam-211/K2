static KEY: std::sync::Mutex<Option<String>> = std::sync::Mutex::new(None);

#[cfg(test)]
thread_local! {
    static TEST_KEY: std::cell::RefCell<Option<Option<String>>> = const { std::cell::RefCell::new(None) };
}

/// Tests: this thread's key (`Some(None)`: none in the vault; `None`: the
/// real lookup, which a test never reaches).
#[cfg(test)]
pub(crate) fn set_test_key(k: Option<Option<String>>) {
    TEST_KEY.with(|c| *c.borrow_mut() = k);
}

fn vault_get() -> Result<Option<String>, CredError> {
    #[cfg(test)]
    {
        if let Some(k) = TEST_KEY.with(|c| c.borrow().clone()) {
            return Ok(k);
        }
        Err(CredError::VaultClosed)
    }
    #[cfg(not(test))]
    {
        use k2_vault::{Requester, Scope, SecretStore, Selector, Use};
        let v = crate::vault::get().map_err(|_| CredError::VaultClosed)?;
        let sel = Selector::system(Scope::engine(super::engine::VAULT_ENGINE), VAULT_NAME);
        match v.resolve(&sel, Use::System, &Requester::System(super::engine::VAULT_SUBSYSTEM.into())) {
            Ok(r) => String::from_utf8(r.value.expose().to_vec()).map(Some).map_err(|_| CredError::Vault("not_utf8".into())),
            Err(e) if e.status == 404 || e.code == "secret_not_active" => Ok(None),
            Err(e) => Err(CredError::Vault(e.code.to_string())),
        }
    }
}

#[cfg(not(test))]
fn vault_put(key: &str) -> Result<(), CredError> {
    use k2_vault::{Actor, Delivery, Kind, Namespace, PutMode, PutRequest, Scope, SecretBytes, SecretStore};
    let v = crate::vault::get().map_err(|_| CredError::VaultClosed)?;
    let mut r = PutRequest::new(Namespace::System, Scope::engine(super::engine::VAULT_ENGINE), VAULT_NAME.to_string(), Kind::Generic);
    r.default_delivery = Some(Delivery::None);
    r.delivery_ceiling = Some(Delivery::None);
    r.origin = format!("system:{}", super::engine::VAULT_SUBSYSTEM);
    r.description = "The key the local mail server signs its delivery webhook with; daemon-only.".to_string();
    r.mode = PutMode::Upsert;
    r.idempotent = true;
    v.put(r, SecretBytes::from_slice(key.as_bytes()), &Actor::System(super::engine::VAULT_SUBSYSTEM.into()))
        .map(|_| ())
        .map_err(|e| CredError::Vault(e.code.to_string()))
}

/// The signing key (cached once read; tests read their thread's key
/// every time).
pub fn key() -> Result<Option<String>, CredError> {
    if cfg!(test) {
        return vault_get();
    }
    if let Some(k) = KEY.lock().unwrap_or_else(|e| e.into_inner()).clone() {
        return Ok(Some(k));
    }
    let k = vault_get()?;
    if let Some(k) = &k {
        *KEY.lock().unwrap_or_else(|e| e.into_inner()) = Some(k.clone());
    }
    Ok(k)
}

/// A new random key: 32 bytes, base64url.
fn new_key() -> Result<String, String> {
    use base64::Engine as _;
    let mut b = [0u8; 32];
    getrandom::getrandom(&mut b).map_err(|e| format!("no randomness: {e}"))?;
    Ok(base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(b))
}

/// The key, made and stored on first use.
#[cfg(not(test))]
fn ensure_key() -> Result<String, String> {
    match key() {
        Ok(Some(k)) => return Ok(k),
        Ok(None) => {}
        Err(e) => return Err(e.to_fail().code.to_string()),
    }
    let k = new_key()?;
    vault_put(&k).map_err(|e| e.to_fail().code.to_string())?;
    *KEY.lock().unwrap_or_else(|e| e.into_inner()) = Some(k.clone());
    Ok(k)
}

// ── the route ───────────────────────────────────────────────────────

fn refuse(f: Fail) -> CliResponse {
    super::fail_response(&f)
}

/// `POST /cli/email/events`. `loopback`: the request came in on the
/// loopback listener, not proxied. `head`: the request head (for the
/// signature header).
pub fn handle(loopback: bool, head: &str, body: &[u8]) -> CliResponse {
    if !wanted() {
        return CliResponse::not_found();
    }
    if !loopback {
        return refuse(fail(403, "forbidden", "the mail server's webhook is served on this machine only"));
    }
    let key = match key() {
        Ok(Some(k)) => k,
        Ok(None) => return refuse(fail(503, "not_ready", "the webhook's key isn't set up yet")),
        Err(e) => return refuse(e.to_fail()),
    };
    if !signature_ok(&key, body, header(head, "x-signature")) {
        k2_core::log_debug!("[email-notify] WARN webhook: a batch with a bad or missing signature was refused");
        return refuse(fail(401, "bad_signature", "the batch isn't signed with this server's webhook key"));
    }
    let events = match parse_events(body) {
        Ok(e) => e,
        Err(why) => return refuse(fail(400, "usage", why)),
    };
    let a = apply(&events, super::now());
    if a.linked + a.missed + a.recorded > 0 {
        k2_core::log_debug!(
            "[email-notify] webhook: {} event(s), {} linked, {} already left the queue, {} outcome(s)",
            events.len(),
            a.linked,
            a.missed,
            a.recorded
        );
    }
    CliResponse::ok_json(
        json!({ "ok": true, "events": events.len(), "linked": a.linked, "recorded": a.recorded, "forwards": a.forwards }).to_string(),
    )
}

