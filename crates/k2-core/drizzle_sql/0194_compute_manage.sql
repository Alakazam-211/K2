-- `projects.agents_can_manage_compute` — the per-agent "Allow managing
-- compute nodes" switch (`compute_manage`). Default 0 (off). With it on, a
-- local agent passport from the workspace may mint enroll codes, confirm,
-- rename, pause/drain/resume, retire and route nodes, and grant/revoke any
-- workspace; every such act writes an Access Audit line. Preview on/off
-- and node remove stay with the owner. Written only by
-- POST /cli/agent-access/set {toggle: "compute_manage"} (the owner only),
-- never by workspace/set, so an agent can never grant it to itself.
ALTER TABLE projects ADD COLUMN agents_can_manage_compute INTEGER NOT NULL DEFAULT 0;
