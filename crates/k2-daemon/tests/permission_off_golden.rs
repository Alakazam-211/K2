struct Env {
    home: PathBuf,
    prev_home: Option<std::ffi::OsString>,
    _guard: std::sync::MutexGuard<'static, ()>,
}

impl Drop for Env {
    fn drop(&mut self) {
        match self.prev_home.take() {
            Some(p) => std::env::set_var("HOME", p),
            None => std::env::remove_var("HOME"),
        }
        for k in ["K2_COMPUTE", "K2_APPS", k2_core::push::ENV_GATEWAY_URL, k2_core::push::ENV_GATEWAY_TOKEN] {
            std::env::remove_var(k);
        }
        let _ = std::fs::remove_dir_all(&self.home);
    }
}

fn setup() -> Env {
    let guard = TEST_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    // Never inherit a real session's switches or identity.
    for (k, _) in std::env::vars() {
        if k.starts_with("K2_") || k.starts_with("K2SO_") {
            std::env::remove_var(k);
        }
    }
    let nanos = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos();
    let home = k2_core::test_env::short_tmp(format!("k2pog{:x}", nanos % 0xffff_ffff));
    std::fs::create_dir_all(&home).unwrap();
    let home = dunce::canonicalize(&home).unwrap();
    let env = Env { prev_home: std::env::var_os("HOME"), home: home.clone(), _guard: guard };
    std::env::set_var("HOME", &home);
    env
}

// ── golden files ─────────────────────────────────────────────────────

fn golden_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../tests/golden/permission_off/daemon")
}

fn blessing() -> bool {
    std::env::var("PERMISSION_GOLDEN_BLESS").as_deref() == Ok("1")
}

/// Compare `got` with the golden at `rel` (or write it when blessing).
/// Differences are collected so one run reports every drifted case.
struct Goldens {
    failures: Vec<String>,
    seen: Vec<PathBuf>,
}

impl Goldens {
    fn new() -> Self {
        Goldens { failures: Vec::new(), seen: Vec::new() }
    }

    fn check(&mut self, rel: &str, got: &str) {
        // Golden names end in .txt or .golden: the repo's .gitignore ignores
        // names like AGENTS.md / SKILL.md / CLAUDE.md, and an ignored golden
        // passes locally but is never committed (the mini run then fails).
        assert!(
            rel.ends_with(".txt") || rel.ends_with(".golden"),
            "golden file {rel:?} must end in .txt or .golden so .gitignore can't drop it"
        );
        let path = golden_root().join(rel);
        self.seen.push(path.clone());
        if blessing() {
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, got).unwrap();
            return;
        }
        match std::fs::read_to_string(&path) {
            Err(e) => self.failures.push(format!(
                "{rel}: no golden ({e}); capture it from a base without cards code with PERMISSION_GOLDEN_BLESS=1"
            )),
            Ok(want) if want == got => {}
            Ok(want) => self.failures.push(format!("{rel} differs from today's answer\n--- want\n{want}\n--- got\n{got}")),
        }
    }

    /// Every golden on disk under `dir` was compared: a dropped or renamed
    /// case fails instead of silently shrinking the net.
    fn assert_complete(&mut self, dir: &str) {
        if blessing() {
            return;
        }
        let root = golden_root().join(dir);
        let mut on_disk = Vec::new();
        collect_files(&root, &mut on_disk);
        for f in on_disk {
            if !self.seen.contains(&f) {
                self.failures.push(format!("{}: golden on disk but no case compared it", f.display()));
            }
        }
    }

    fn finish(self) {
        if blessing() {
            eprintln!("blessed {} golden files under {}", self.seen.len(), golden_root().display());
            return;
        }
        assert!(
            self.failures.is_empty(),
            "{} off-golden failure(s):\n\n{}",
            self.failures.len(),
            self.failures.join("\n\n")
        );
    }
}

fn collect_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            collect_files(&p, out);
        } else {
            out.push(p);
        }
    }
}

// ── normalizer ───────────────────────────────────────────────────────

struct Norm {
    subs: Vec<(String, String)>,
}

impl Norm {
    fn apply(&self, s: &str) -> String {
        let mut t = s.to_string();
        // Longest first so a path is replaced before its prefix.
        let mut subs = self.subs.clone();
        subs.sort_by(|a, b| b.0.len().cmp(&a.0.len()));
        for (from, to) in &subs {
            if !from.is_empty() {
                t = t.replace(from.as_str(), to);
            }
        }
        replace_prefixed_ids(&replace_uuids(&t))
    }
}

/// Any remaining 8-4-4-4-12 hex string → `<UUID>`. UUIDs are ASCII, so
/// the text is scanned in ASCII runs and other characters pass through.
fn replace_uuids(s: &str) -> String {
    let mut res = String::with_capacity(s.len());
    let mut rest = s;
    while !rest.is_empty() {
        let ascii_end = rest.find(|c: char| !c.is_ascii()).unwrap_or(rest.len());
        res.push_str(&replace_uuids_ascii(&rest[..ascii_end]));
        rest = &rest[ascii_end..];
        if let Some(c) = rest.chars().next() {
            res.push(c);
            rest = &rest[c.len_utf8()..];
        }
    }
    res
}

fn replace_uuids_ascii(s: &str) -> String {
    debug_assert!(s.is_ascii());
    let b = s.as_bytes();
    let shape = [8usize, 4, 4, 4, 12];
    let mut out = String::with_capacity(s.len());
    let mut i = 0;
    'outer: while i < b.len() {
        let mut j = i;
        for (n, len) in shape.iter().enumerate() {
            for _ in 0..*len {
                if j >= b.len() || !b[j].is_ascii_hexdigit() {
                    out.push(b[i] as char);
                    i += 1;
                    continue 'outer;
                }
                j += 1;
            }
            if n < 4 {
                if j >= b.len() || b[j] != b'-' {
                    out.push(b[i] as char);
                    i += 1;
                    continue 'outer;
                }
                j += 1;
            }
        }
        let before_ok = i == 0 || !b[i - 1].is_ascii_hexdigit();
        let after_ok = j >= b.len() || !b[j].is_ascii_hexdigit();
        if before_ok && after_ok {
            out.push_str("<UUID>");
            i = j;
        } else {
            out.push(b[i] as char);
            i += 1;
        }
    }
    out
}

// ── transports ───────────────────────────────────────────────────────

struct Resp {
    status_line: String,
    content_type: String,
    body: String,
}

fn parse_resp(text: &str) -> Resp {
    let status_line = text.lines().next().unwrap_or_else(|| panic!("no status line: {text:?}")).trim_end().to_string();
    assert!(status_line.starts_with("HTTP/1."), "not an HTTP response: {text:?}");
    let (head, body) = text.split_once("\r\n\r\n").unwrap_or((text, ""));
    let content_type = head
        .lines()
        .find_map(|l| {
            let (k, v) = l.split_once(':')?;
            k.eq_ignore_ascii_case("content-type").then(|| v.trim().to_string())
        })
        .unwrap_or_default();
    Resp { status_line, content_type, body: body.to_string() }
}

fn tcp_blocking(port: u16, method: &str, pq: &str, body: Option<String>) -> Resp {
    let mut s = StdTcpStream::connect(("127.0.0.1", port)).expect("connect");
    s.set_read_timeout(Some(Duration::from_secs(30))).unwrap();
    let raw = match body {
        Some(b) => format!(
            "{method} {pq} HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\nContent-Type: application/json\r\nContent-Length: {}\r\n\r\n{b}",
            b.len()
        ),
        None => format!("{method} {pq} HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n"),
    };
    s.write_all(raw.as_bytes()).unwrap();
    let mut out = Vec::new();
    let mut chunk = [0u8; 8192];
    loop {
        match s.read(&mut chunk) {
            Ok(0) => break,
            Ok(n) => out.extend_from_slice(&chunk[..n]),
            Err(e) if e.kind() == std::io::ErrorKind::ConnectionReset => break,
            Err(e) => panic!("{method} {pq}: {e}"),
        }
    }
    parse_resp(&String::from_utf8_lossy(&out))
}

fn enc(s: &str) -> String {
    s.bytes()
        .map(|b| if b.is_ascii_alphanumeric() || b"-_.~".contains(&b) { (b as char).to_string() } else { format!("%{b:02X}") })
        .collect()
}

/// TCP with `token` as `?token=` (the CLI's form), or no credential.
async fn tcp(port: u16, method: &str, path_q: &str, token: Option<&str>, body: Option<&str>) -> Resp {
    let pq = match token {
        Some(t) => {
            let sep = if path_q.contains('?') { '&' } else { '?' };
            format!("{path_q}{sep}token={}", enc(t))
        }
        None => path_q.to_string(),
    };
    let method = method.to_string();
    let body = body.map(str::to_string);
    tokio::task::spawn_blocking(move || tcp_blocking(port, &method, &pq, body)).await.unwrap()
}

/// The agent's own cell socket, passport as a Bearer (the CLI's UDS form).
async fn cell(sock: &Path, method: &str, path_q: &str, bearer: &str, body: Option<&str>) -> Resp {
    let raw = match body {
        Some(b) => format!(
            "{method} {path_q} HTTP/1.1\r\nHost: localhost\r\nAuthorization: Bearer {bearer}\r\nContent-Type: application/json\r\nContent-Length: {}\r\n\r\n{b}",
            b.len()
        ),
        None => format!("{method} {path_q} HTTP/1.1\r\nHost: localhost\r\nAuthorization: Bearer {bearer}\r\n\r\n"),
    };
    let mut stream = UnixStream::connect(sock).await.expect("connect cell socket");
    stream.write_all(raw.as_bytes()).await.expect("write request");
    stream.flush().await.ok();
    let mut buf: Vec<u8> = Vec::new();
    let mut chunk = [0u8; 8192];
    loop {
        match stream.read(&mut chunk).await {
            Ok(0) => break,
            Ok(n) => buf.extend_from_slice(&chunk[..n]),
            Err(_) => break,
        }
    }
    parse_resp(&String::from_utf8_lossy(&buf))
}

fn render(label: &str, method: &str, path_q: &str, body: Option<&str>, r: &Resp) -> String {
    format!(
        "## {label}\n> {method} {path_q}\n> body: {}\n{}\ncontent-type: {}\n{}\n",
        body.unwrap_or(""),
        r.status_line,
        r.content_type,
        r.body
    )
}

// ── structured captures (Thread items, frames, pushes) ───────────────

/// Keys whose values are clocks, counters or per-run tokens. Their VALUES
/// become `"<key>"`; the key itself is kept, so a field that appears or
/// disappears still fails the golden.
const VOLATILE_KEYS: &[&str] = &[
    "created_at",
    "createdAt",
    "updated_at",
    "updatedAt",
    "expiresAt",
    "expires_at",
    "answeredAt",
    "requestedAt",
    "at",
    "rev",
    "instanceId",
    "badgeKey",
    "lastActivityAt",
    "ts",
    // An App's loopback front port (allocated per run).
    "frontPort",
];

fn mask_volatile(v: &mut Value) {
    match v {
        Value::Object(m) => {
            for (k, x) in m.iter_mut() {
                if VOLATILE_KEYS.contains(&k.as_str()) && !x.is_null() {
                    *x = Value::String(format!("<{k}>"));
                } else {
                    mask_volatile(x);
                }
            }
        }
        Value::Array(a) => a.iter_mut().for_each(mask_volatile),
        _ => {}
    }
}

/// A JSON body, volatile values masked, pretty-printed (keys are already
/// sorted: serde_json has no preserve_order here).
fn json_text(body: &str) -> String {
    match serde_json::from_str::<Value>(body) {
        Ok(mut v) => {
            mask_volatile(&mut v);
            serde_json::to_string_pretty(&v).unwrap()
        }
        Err(_) => body.to_string(),
    }
}

fn render_json(label: &str, method: &str, path_q: &str, body: Option<&str>, r: &Resp) -> String {
    format!(
        "## {label}\n> {method} {path_q}\n> body: {}\n{}\ncontent-type: {}\n{}\n",
        body.unwrap_or(""),
        r.status_line,
        r.content_type,
        json_text(&r.body)
    )
}

/// A wall's answer: a refusal byte for byte; a held 2xx answer (it carries
/// request ids and clocks) as masked JSON.
fn render_wall(label: &str, method: &str, path_q: &str, body: Option<&str>, r: &Resp) -> String {
    if r.status_line.contains(" 20") {
        render_json(label, method, path_q, body, r)
    } else {
        render(label, method, path_q, body, r)
    }
}

/// One wall over TCP and the agent's cell socket, checked as `walls/<id>.txt`.
#[allow(clippy::too_many_arguments)]
async fn wall_case(
    g: &mut Goldens,
    norm: &Norm,
    port: u16,
    sock: &Path,
    passport: &str,
    id: &str,
    action: &str,
    method: &str,
    path_q: &str,
    body: Option<&str>,
) {
    let t = tcp(port, method, path_q, Some(passport), body).await;
    let c = cell(sock, method, path_q, passport, body).await;
    let text = format!(
        "# {id} — stands for catalog row `{action}`\n{}{}",
        render_wall("tcp (agent passport)", method, path_q, body, &t),
        render_wall("cell socket (same passport)", method, path_q, body, &c),
    );
    g.check(&format!("walls/{id}.txt"), &norm.apply(&text));
}

/// `w_<12 hex>` (held App requests) and `out_<hex>` (held mail sends) → a
/// placeholder; both are random per run.
fn replace_prefixed_ids(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    'scan: while !rest.is_empty() {
        for (prefix, tag) in [("w_", "<W_ID>"), ("out_", "<OUT_ID>")] {
            if let Some(after) = rest.strip_prefix(prefix) {
                let before_ok = out.chars().last().is_none_or(|c| !c.is_ascii_alphanumeric() && c != '_');
                let n = after.bytes().take_while(|b| b.is_ascii_hexdigit()).count();
                if before_ok && n >= 8 {
                    out.push_str(tag);
                    rest = &after[n..];
                    continue 'scan;
                }
            }
        }
        let c = rest.chars().next().unwrap();
        out.push(c);
        rest = &rest[c.len_utf8()..];
    }
    out
}

// The fake push gateway (loopback; nothing leaves the machine): every
// `/push/dispatch` body the daemon POSTs. Pattern from
// tests/thread_read_integration.rs.
fn gateway_calls() -> &'static StdMutex<Vec<Value>> {
    static CALLS: OnceLock<StdMutex<Vec<Value>>> = OnceLock::new();
    CALLS.get_or_init(|| StdMutex::new(Vec::new()))
}

fn ensure_fake_gateway() {
    static URL: OnceLock<String> = OnceLock::new();
    let url = URL.get_or_init(|| {
        let listener = StdTcpListener::bind("127.0.0.1:0").expect("bind fake gateway");
        let port = listener.local_addr().expect("addr").port();
        std::thread::spawn(move || {
            for stream in listener.incoming() {
                let Ok(stream) = stream else { continue };
                std::thread::spawn(move || serve_gateway(stream));
            }
        });
        format!("http://127.0.0.1:{port}")
    });
    std::env::set_var(k2_core::push::ENV_GATEWAY_URL, url);
    std::env::set_var(k2_core::push::ENV_GATEWAY_TOKEN, "fake-gateway-token");
}

fn serve_gateway(stream: StdTcpStream) {
    let mut reader = BufReader::new(stream.try_clone().expect("clone"));
    let mut len = 0usize;
    let mut line = String::new();
    loop {
        line.clear();
        if reader.read_line(&mut line).unwrap_or(0) == 0 {
            return;
        }
        let l = line.trim_end();
        if l.is_empty() {
            break;
        }
        if let Some((k, v)) = l.split_once(':') {
            if k.eq_ignore_ascii_case("content-length") {
                len = v.trim().parse().unwrap_or(0);
            }
        }
    }
    let mut body = vec![0u8; len];
    reader.read_exact(&mut body).expect("gateway body");
    let v: Value = serde_json::from_slice(&body).expect("gateway got JSON");
    gateway_calls().lock().expect("calls").push(v);
    let reply = r#"{"results":[]}"#;
    let mut out = stream;
    let _ = out.write_all(
        format!("HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{reply}", reply.len())
            .as_bytes(),
    );
}

fn gateway_mark() -> usize {
    gateway_calls().lock().expect("calls").len()
}

/// Whole dispatch bodies since `mark` for conversation `conv`: waits up to
/// 8 s for `want` of them, then (want = 0) a fixed 1.5 s quiet window.
async fn pushes_since(mark: usize, conv: &str, want: usize) -> Vec<Value> {
    let deadline = Instant::now() + Duration::from_secs(if want == 0 { 2 } else { 8 });
    if want == 0 {
        tokio::time::sleep(Duration::from_millis(1500)).await;
    }
    loop {
        let got: Vec<Value> = gateway_calls().lock().expect("calls")[mark..]
            .iter()
            .filter(|c| c["payload"]["data"]["conversationId"] == conv)
            .cloned()
            .collect();
        if got.len() >= want || Instant::now() > deadline {
            return got;
        }
        tokio::time::sleep(Duration::from_millis(25)).await;
    }
}

type WsSocket = tokio_tungstenite::WebSocketStream<tokio_tungstenite::MaybeTlsStream<tokio::net::TcpStream>>;

async fn open_ws(port: u16, conv: &str, token: &str) -> WsSocket {
    let url = format!("ws://127.0.0.1:{port}/cli/overlay/events?conversation={conv}&token={}", enc(token));
    let (ws, _) = tokio_tungstenite::connect_async(&url).await.unwrap_or_else(|e| panic!("overlay WS for {conv}: {e}"));
    ws
}

/// The Thread frame for doc `id` (activity frames and pings skipped).
async fn frame_for(ws: &mut WsSocket, id: &str, what: &str) -> Value {
    use tokio_tungstenite::tungstenite::Message;
    let deadline = tokio::time::Instant::now() + Duration::from_secs(8);
    loop {
        let left = deadline.saturating_duration_since(tokio::time::Instant::now());
        let msg = tokio::time::timeout(left, ws.next())
            .await
            .unwrap_or_else(|_| panic!("timed out waiting for the overlay frame: {what}"))
            .unwrap_or_else(|| panic!("overlay WS closed waiting for: {what}"))
            .unwrap_or_else(|e| panic!("overlay WS error waiting for {what}: {e}"));
        if let Message::Text(t) = msg {
            let f: Value = serde_json::from_str(&t).unwrap_or_else(|e| panic!("frame JSON ({e}): {t}"));
            if f["collection"] == "thread" && f["id"] == id {
                return f;
            }
        }
    }
}

