    /// TUWA4: every output on disk equals a fresh render. Never rewrites.
    #[test]
    fn generated_files_are_fresh() {
        let rt = runtime();
        let outs = render(catalog(), rt.as_deref()).unwrap_or_else(|e| panic!("{e}"));
        let mut stale = Vec::new();
        for o in &outs {
            let on_disk = if o.path == CLI {
                let cli = read(CLI);
                cli_block_in(&cli).unwrap_or_else(|e| panic!("{e}; {REGEN}")).to_string()
            } else {
                read(o.path)
            };
            if on_disk != o.text {
                stale.push(o.path);
            }
        }
        assert!(stale.is_empty(), "stale generated files {stale:?}: {REGEN}");
    }

