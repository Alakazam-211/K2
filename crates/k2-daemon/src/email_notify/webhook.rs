//! The local mail server's delivery webhook (prd-email-notifications-
//! part2-v1 §4 N6 item 3; vs-live EN-A25, EN-A27).
//!
//! ```text
//! POST /cli/email/events   the local Stalwart only: loopback, HMAC-signed (X-Signature)
//! ```
//!
//! **What it gives.** Stalwart posts `queue.*` and `delivery.*` events
//! (`{events:[{id,createdAt,type,data}]}`). K2 turns them into two outcomes
//! per recipient: `delivered` and `delayed`. Delivery reports in the
//! sender's mailbox stay the truth for bounces and complaints
//! ([`super::outcomes`]); nothing here records a bounce, suppresses an
//! address or pauses a sender.
//!
//! **The link to a send.** The payload carries the mail server's `queueId`
//! but no envelope id. On the first event for a message (the queued event,
//! whose `from` is one of K2's hosted senders' envelope accounts), K2
//! encodes the number as a registry id ([`registry_id`]), reads that
//! `x:QueuedMessage`'s `envId` (K2 submits with `ENVID=<log id>`), checks
//! it is that sender's send, and keeps the pair (k2.db 0248, 7 days). Later
//! events join on it. A message that already left the queue gets no pair:
//! its recipients stay `submitted`. K2 never guesses from times or
//! recipients. Mail K2 didn't send is never looked up.
//!
//! **Trust.** The route answers only on the loopback listener (a proxied
//! or tunnelled request is not loopback) and only with a valid
//! `X-Signature`: base64 HMAC-SHA256 of the body under a key K2 keeps in
//! the vault (system namespace, `engine:email-notify`, `webhook-hmac`).
//! No token: the signature is the credential. With the box switch off
//! (and no outside forward live) the route answers as an unknown route does.
//!
//! **Configuration.** K2 keeps exactly one `x:WebHook` of its own (its URL
//! is `http://127.0.0.1:<daemon port>/cli/email/events`), written at every
//! daemon start, after `hostmail enable` and after `hostmail upgrade`
//! ([`spawn_after`]); idempotent: it writes only when the URL, the event
//! list or the key changed. The key isn't readable back from the mail
//! server, so the object carries a non-secret `X-K2-Key-Id` header (a
//! hash prefix of the key) that tells K2 which key it holds. Box switch
//! off and no outside forward live: K2 removes its webhook (an outside
//! forward's change asks again, [`spawn_after`]`("forward")`). Other
//! webhooks are never touched.
//!
//! The forwarding PRD reads the same events (`queue.autogenerated-queued`,
//! `delivery.delivered`, `delivery.dsn-perm-fail`, `delivery.failed`)
//! through [`parse_events`]: [`crate::mail::forward_outcomes`]. While any
//! outside forward is live the webhook stays on and the route answers,
//! even with the box switch off.

