/// One rendered file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Output {
    pub path: &'static str,
    pub text: String,
}

/// Every output. `runtime` is `sdk/k2-runtime.js` when it exists. The
/// `cli/k2` entry is only the fenced block (markers included).
pub fn render(c: &Catalog, runtime: Option<&str>) -> Result<Vec<Output>, String> {
    let probs = super::lint::lint(c);
    if !probs.is_empty() {
        return Err(format!("{CATALOG_PATH} doesn't lint clean:\n{}", probs.join("\n")));
    }
    let mut out = vec![
        Output { path: ZEN_VERBS_TS, text: zen_verbs_ts(c) },
        Output { path: CAPS_TS, text: caps_ts(c) },
        Output { path: K2_DTS, text: k2_dts(c)? },
        Output { path: K2_FRAME_JS, text: frame_js(c, runtime) },
        Output { path: CLI, text: cli_block(c) },
    ];
    let snapshot = snapshot_json(c, runtime, &out);
    out.push(Output { path: SNAPSHOT_JSON, text: snapshot });
    Ok(out)
}

/// The fenced block's text inside a whole `cli/k2`, markers included.
pub fn cli_block_in(cli: &str) -> Result<&str, String> {
    let start = cli.find(CLI_BEGIN).ok_or_else(|| format!("{CLI} has no '{CLI_BEGIN}' line"))?;
    let rest = &cli[start..];
    let end = rest.find(CLI_END).ok_or_else(|| format!("{CLI} has no '{CLI_END}' line after the begin marker"))?;
    let end_line = rest[end..].find('\n').map(|i| end + i + 1).unwrap_or(rest.len());
    Ok(&rest[..end_line])
}

/// `cli` with its fenced block replaced by `block`.
pub fn splice_cli(cli: &str, block: &str) -> Result<String, String> {
    let old = cli_block_in(cli)?;
    let at = cli.find(old).expect("block was found in cli");
    Ok(format!("{}{}{}", &cli[..at], block, &cli[at + old.len()..]))
}

pub fn sha256_hex(bytes: &[u8]) -> String {
    let d = Sha256::digest(bytes);
    d.iter().map(|b| format!("{b:02x}")).collect()
}

// ── Shared helpers (also read by the k2-zen skill) ───────────────────────

fn ts_str(s: &str) -> String {
    if s.contains('\'') && !s.contains('"') {
        format!("\"{}\"", s.replace('\\', "\\\\"))
    } else {
        format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
    }
}

/// Object keys in byte order, whatever map the JSON parser keeps, so the
/// outputs never depend on serde_json's `preserve_order` feature.
fn sorted_keys(m: &serde_json::Map<String, J>) -> Vec<String> {
    let mut k: Vec<String> = m.keys().cloned().collect();
    k.sort();
    k
}

fn arg_title(a: &J) -> &str {
    a.get("title").and_then(J::as_str).unwrap_or("arg")
}

fn arg_optional(a: &J) -> bool {
    a.get("default").is_some()
}

/// How a verb reads in prose: `thread.read(address, {beforeSeq, limit})`,
/// `controls.bind(kind, element, gardenId?)`, `agents.subscribe(cb)`.
pub fn signature(v: &VerbRow) -> String {
    let mut args: Vec<String> = request_items(v)
        .iter()
        .map(|a| {
            let props = a.get("properties").and_then(J::as_object).filter(|p| !p.is_empty());
            match props {
                Some(p) => format!("{{{}}}", sorted_keys(p).join(", ")),
                None if arg_optional(a) => format!("{}?", arg_title(a)),
                None => arg_title(a).to_string(),
            }
        })
        .collect();
    if matches!(v.kind, VerbKind::Subscribe | VerbKind::Event) {
        args.push("cb".into());
    }
    format!("{}({})", v.verb, args.join(", "))
}

/// Rows with a `builtin` or `registered` renderer binding: today's
/// `ZEN_VERBS`, in catalog order.
pub fn bridge_rows(c: &Catalog) -> Vec<&VerbRow> {
    c.verbs
        .iter()
        .filter(|v| {
            matches!(
                v.bindings.renderer.as_ref().map(|r| r.implementation),
                Some(RendererImpl::Builtin | RendererImpl::Registered)
            )
        })
        .collect()
}

/// Widget rows grouped by cap: no cap first, then the cap table's order.
pub fn widget_groups(c: &Catalog) -> Vec<(Option<&str>, Vec<&VerbRow>)> {
    let rows = c.verbs_exposed_to(Exposure::Widget);
    let mut out: Vec<(Option<&str>, Vec<&VerbRow>)> = Vec::new();
    let mut keys: Vec<Option<&str>> = vec![None];
    keys.extend(c.caps.iter().map(|cap| Some(cap.name.as_str())));
    for k in keys {
        let group: Vec<&VerbRow> = rows.iter().copied().filter(|v| v.cap.as_deref() == k).collect();
        if !group.is_empty() {
            out.push((k, group));
        }
    }
    out
}

fn generated_header(comment: &str, what: &str) -> String {
    format!(
        "{comment} GENERATED by contract-gen from {CATALOG_PATH}{what}.\n\
         {comment} Do not edit: change the catalog, then {REGEN}\n\
         {comment} (prd-zen-user-widgets-v2 UWA11). The freshness tests fail on drift.\n"
    )
}

// ── zen-verbs.generated.ts ───────────────────────────────────────────────

fn zen_verbs_ts(c: &Catalog) -> String {
    let mut s = generated_header("//", "");
    s.push_str("\nimport type { CatalogReach, CatalogVerbKind } from '../contract/catalog-types'\n\n");
    s.push_str("/** The catalog version this table was generated from. */\n");
    s.push_str(&format!("export const ZEN_CATALOG_VERSION = {}\n\n", c.catalog_version));
    s.push_str(
        "/**\n * Every catalog row with a `builtin` or `registered` renderer binding,\n * verb → cap (UWA4). The renderer's bridge table for K2's own widgets.\n */\nexport const ZEN_VERBS = {\n",
    );
    for v in bridge_rows(c) {
        let cap = v.cap.as_deref().map(ts_str).unwrap_or_else(|| "null".into());
        s.push_str(&format!("  {}: {cap},\n", ts_str(&v.verb)));
    }
    s.push_str("} as const satisfies Record<string, string | null>\n\n");
    let caps = c.caps_exposed_to(Exposure::Widget).iter().map(|x| ts_str(x)).collect::<Vec<_>>().join(" | ");
    s.push_str("/** One custom-widget verb: its cap, portable or local, and how it answers. */\n");
    s.push_str("export interface ZenCustomVerbRow {\n");
    s.push_str(&format!("  readonly cap: {caps} | null\n"));
    s.push_str("  readonly reach: CatalogReach\n  readonly kind: CatalogVerbKind\n}\n\n");
    s.push_str(
        "/**\n * The custom-widget allowlist (UW16, UWB10): catalog rows whose `exposure`\n * includes `widget`, grouped by cap. Its own table, never `ZEN_VERBS`.\n */\nexport const ZEN_CUSTOM_VERBS = {\n",
    );
    for (_, rows) in widget_groups(c) {
        for v in rows {
            let cap = v.cap.as_deref().map(ts_str).unwrap_or_else(|| "null".into());
            s.push_str(&format!(
                "  {}: {{ cap: {cap}, reach: {}, kind: {} }},\n",
                ts_str(&v.verb),
                ts_str(reach_name(v)),
                ts_str(kind_name(v.kind))
            ));
        }
    }
    s.push_str("} as const satisfies Record<string, ZenCustomVerbRow>\n\n");
    s.push_str("export type ZenCustomVerb = keyof typeof ZEN_CUSTOM_VERBS\n");
    s
}

fn reach_name(v: &VerbRow) -> &'static str {
    match v.reach {
        super::Reach::Portable => "portable",
        super::Reach::Local => "local",
    }
}

fn kind_name(k: VerbKind) -> &'static str {
    match k {
        VerbKind::Call => "call",
        VerbKind::Subscribe => "subscribe",
        VerbKind::Event => "event",
    }
}

fn exposure_name(e: &Exposure) -> &'static str {
    match e {
        Exposure::Widget => "widget",
        Exposure::App => "app",
    }
}

// ── k2-caps.generated.ts ─────────────────────────────────────────────────

fn caps_ts(c: &Catalog) -> String {
    let mut s = generated_header("//", " (`caps`)");
    s.push_str(
        "// Read by Settings → Apps (`label`, UWA9) and the guide.\n\n",
    );
    s.push_str("import type { CatalogExposure } from './contract/catalog-types'\n\n");
    s.push_str(
        "export interface K2CapInfo {\n  readonly label: string\n  /** A plain sentence for the cap; `{where}` is the agents' words. */\n  readonly sentence?: string\n  readonly exposure: readonly CatalogExposure[]\n}\n\n",
    );
    s.push_str("export const K2_CAPS = {\n");
    for cap in &c.caps {
        let exposure = cap.exposure.iter().map(|e| ts_str(exposure_name(e))).collect::<Vec<_>>().join(", ");
        match &cap.sentence {
            Some(sentence) => s.push_str(&format!(
                "  {}: {{\n    label: {},\n    sentence: {},\n    exposure: [{exposure}],\n  }},\n",
                ts_str(&cap.name),
                ts_str(&cap.label),
                ts_str(sentence)
            )),
            None => s.push_str(&format!(
                "  {}: {{ label: {}, exposure: [{exposure}] }},\n",
                ts_str(&cap.name),
                ts_str(&cap.label)
            )),
        }
    }
    s.push_str("} as const satisfies Record<string, K2CapInfo>\n\n");
    s.push_str("export type K2Cap = keyof typeof K2_CAPS\n\n");
    let widget = c.caps_exposed_to(Exposure::Widget).iter().map(|x| ts_str(x)).collect::<Vec<_>>().join(", ");
    s.push_str("/** Caps a custom widget may ask for (= the Rust `USER_WIDGET_CAPS`). */\n");
    s.push_str(&format!("export const USER_WIDGET_CAPS = [{widget}] as const\n\n"));
    s.push_str("export type UserWidgetCap = (typeof USER_WIDGET_CAPS)[number]\n");
    s
}

// ── k2.d.ts ──────────────────────────────────────────────────────────────

fn types_of(s: &J) -> Vec<&str> {
    match s.get("type") {
        Some(J::String(t)) => vec![t.as_str()],
        Some(J::Array(a)) => a.iter().filter_map(J::as_str).collect(),
        _ => Vec::new(),
    }
}

/// Named interfaces, in first-use order.
#[derive(Default)]
struct Ts {
    order: Vec<String>,
    bodies: BTreeMap<String, String>,
}

impl Ts {
    /// The TypeScript type of `s`. A titled object becomes a named
    /// interface (registered once).
    fn ty(&mut self, s: &J) -> Result<String, String> {
        if let Some(e) = s.get("enum").and_then(J::as_array) {
            let lits: Vec<String> = e
                .iter()
                .map(|x| match x {
                    J::String(v) => ts_str(v),
                    _ => "null".into(),
                })
                .collect();
            return Ok(lits.join(" | "));
        }
        let types = types_of(s);
        if types.is_empty() {
            return Ok("unknown".into());
        }
        let nullable = types.contains(&"null");
        let mut parts: Vec<String> = Vec::new();
        for t in types.iter().filter(|t| **t != "null") {
            parts.push(match *t {
                "string" => "string".into(),
                "number" | "integer" => "number".into(),
                "boolean" => "boolean".into(),
                "array" => {
                    let item = match s.get("items") {
                        Some(i) => self.ty(i)?,
                        None => "unknown".into(),
                    };
                    if item.contains(' ') {
                        format!("Array<{item}>")
                    } else {
                        format!("{item}[]")
                    }
                }
                "object" => self.object(s)?,
                other => return Err(format!("no TypeScript for type '{other}'")),
            });
        }
        if parts.is_empty() {
            parts.push("null".into());
        } else if nullable {
            parts.push("null".into());
        }
        Ok(parts.join(" | "))
    }

    fn object(&mut self, s: &J) -> Result<String, String> {
        let props = s.get("properties").and_then(J::as_object);
        let Some(props) = props else {
            return Ok(match s.get("additionalProperties") {
                Some(m) if m.is_object() => format!("Record<string, {}>", self.ty(m)?),
                _ => "Record<string, unknown>".into(),
            });
        };
        let required: Vec<&str> =
            s.get("required").and_then(J::as_array).map(|a| a.iter().filter_map(J::as_str).collect()).unwrap_or_default();
        let title = s.get("title").and_then(J::as_str);
        let indent = if title.is_some() { "  " } else { "" };
        let mut fields = Vec::new();
        for k in sorted_keys(props) {
            let p = &props[k.as_str()];
            let t = self.ty(p)?;
            let opt = if required.contains(&k.as_str()) { "" } else { "?" };
            let doc = p.get("description").and_then(J::as_str).map(|d| format!("{indent}/** {d} */\n")).unwrap_or_default();
            if title.is_some() {
                fields.push(format!("{doc}  readonly {k}{opt}: {t}"));
            } else {
                fields.push(format!("{k}{opt}: {t}"));
            }
        }
        match title {
            Some(name) => {
                if !self.bodies.contains_key(name) {
                    // A schema's `description` describes the property that holds
                    // it, so it is written there, never on the interface.
                    let body = format!("export interface {name} {{\n{}\n}}\n", fields.join("\n"));
                    self.order.push(name.to_string());
                    self.bodies.insert(name.to_string(), body);
                }
                Ok(name.to_string())
            }
            None => Ok(format!("{{ {} }}", fields.join("; "))),
        }
    }

    /// An argument's type: its `title` is its name, never a type name.
    fn arg(&mut self, a: &J) -> Result<String, String> {
        let mut a = a.clone();
        if let Some(o) = a.as_object_mut() {
            o.remove("title");
        }
        self.ty(&a)
    }
}

fn helper_doc(v: &VerbRow) -> String {
    let cap = v.cap.as_deref().map(|c| format!("cap {c}")).unwrap_or_else(|| "no cap".into());
    format!("  /** {} {cap} · {} · {}. e.g. `{}` */\n", v.doc, reach_name(v), v.feature, v.example)
}

fn k2_dts(c: &Catalog) -> Result<String, String> {
    let mut ts = Ts::default();
    let mut verbs_map = Vec::new();
    let mut surfaces: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    let mut surface_order: Vec<&str> = Vec::new();
    let mut call_verbs = Vec::new();
    let mut sub_verbs = Vec::new();
    for (_, rows) in widget_groups(c) {
        for v in rows {
            let mut args = Vec::new();
            for a in request_items(v) {
                let t = ts.arg(a)?;
                let opt = if arg_optional(a) { "?" } else { "" };
                args.push(format!("{}{opt}: {t}", arg_title(a)));
            }
            let value = ts.ty(&v.response)?;
            verbs_map.push(format!("  {}: {{ args: [{}]; value: {value} }}", ts_str(&v.verb), args.join(", ")));
            let (surface, action) = v.verb.split_once('.').expect("lint checked surface.action");
            if !surface_order.contains(&surface) {
                surface_order.push(surface);
            }
            let method = match v.kind {
                VerbKind::Call => {
                    call_verbs.push(ts_str(&v.verb));
                    format!("  {action}({}): Promise<{value}>", args.join(", "))
                }
                VerbKind::Subscribe | VerbKind::Event => {
                    sub_verbs.push(ts_str(&v.verb));
                    let mut a = args.clone();
                    a.push(format!("cb: (value: {value}) => void"));
                    a.push("onError?: (error: K2Error) => void".into());
                    format!("  {action}({}): () => void", a.join(", "))
                }
            };
            surfaces.entry(surface).or_default().push(format!("{}{method}", helper_doc(v)));
        }
    }
    let mut s = generated_header("//", "");
    s.push_str(
        "//\n// The `k2` object a custom Garden widget gets in its sealed frame\n// (prd-zen-user-widgets-v2 §7). Named helpers are one per catalog row exposed\n// to `widget`; `k2.call` / `k2.subscribe` reach the same verbs by name.\n\nexport {}\n\n",
    );
    for name in &ts.order {
        s.push_str(&ts.bodies[name]);
        s.push('\n');
    }
    let caps = c.caps_exposed_to(Exposure::Widget).iter().map(|x| ts_str(x)).collect::<Vec<_>>().join(" | ");
    s.push_str(&format!("/** A cap a widget may ask for. */\nexport type K2Cap = {caps}\n\n"));
    let codes = c.errors.iter().map(|e| ts_str(&e.code)).collect::<Vec<_>>().join(" | ");
    s.push_str(&format!("/** The shared error codes (UWA10). */\nexport type K2ErrorCode = {codes}\n\n"));
    s.push_str(
        "/** A refused call rejects with this. */\nexport interface K2Error extends Error {\n  readonly name: 'K2Error'\n  readonly code: K2ErrorCode\n  readonly verb: string\n  readonly cap?: string\n  readonly room?: string\n  readonly feature?: string\n}\n\n",
    );
    s.push_str(&format!(
        "/** Every widget verb: its arguments and what it answers (or pushes). */\nexport interface K2Verbs {{\n{}\n}}\n\n",
        verbs_map.join("\n")
    ));
    s.push_str(&format!("export type K2Verb = keyof K2Verbs\nexport type K2CallVerb = {}\nexport type K2SubscribeVerb = {}\n\n", call_verbs.join(" | "), sub_verbs.join(" | ")));
    s.push_str("export interface K2 {\n");
    for surface in &surface_order {
        s.push_str(&format!("  readonly {surface}: {{\n"));
        for m in &surfaces[surface] {
            for line in m.lines() {
                s.push_str(&format!("  {line}\n"));
            }
        }
        s.push_str("  }\n");
    }
    s.push_str(
        "  /** Any widget verb by name; a refused call rejects with K2Error. */\n  call<V extends K2CallVerb>(verb: V, ...args: K2Verbs[V]['args']): Promise<K2Verbs[V]['value']>\n  /** Subscribe by name; returns the unsubscribe. A refused subscription ends and calls `onError` (the function after `cb`) once with a K2Error; with no `onError` K2 logs it as an uncaught error. */\n  subscribe<V extends K2SubscribeVerb>(\n    verb: V,\n    ...args:\n      | [...K2Verbs[V]['args'], (value: K2Verbs[V]['value']) => void]\n      | [...K2Verbs[V]['args'], (value: K2Verbs[V]['value']) => void, (error: K2Error) => void]\n  ): () => void\n  /** Alias of `subscribe`. */\n  on: K2['subscribe']\n  /** Drawing advice: the verb exists, its cap was allowed and K2 here has its feature. K2 still checks every call. */\n  can(verb: string): boolean\n  /** Tell K2 you have drawn (call once). */\n  ready(): void\n  /** The placement's `config` table from the Garden file. */\n  readonly config: Readonly<Record<string, string | number | boolean>>\n  readonly widget: { readonly id: string; readonly name: string; readonly garden: string }\n  /** A file in the widget's folder as a data: URL, or null. */\n  asset(name: string): string | null\n  readonly motion: { readonly reduced: boolean }\n}\n\ndeclare global {\n  const k2: K2\n  interface Window {\n    readonly k2: K2\n  }\n}\n",
    );
    Ok(s)
}

// ── k2-frame.js ──────────────────────────────────────────────────────────

fn frame_js(c: &Catalog, runtime: Option<&str>) -> String {
    let mut s = generated_header("//", " and sdk/k2-runtime.js");
    s.push_str(
        "// The shared runtime joined with the catalog's widget verb table: one\n// classic script, injected first in every custom widget frame and nonced\n// (UWA5). The runtime reads the table as `K2_CONTRACT`.\n(function () {\n  'use strict'\n",
    );
    let codes = c.errors.iter().map(|e| ts_str(&e.code)).collect::<Vec<_>>().join(", ");
    s.push_str(&format!(
        "  var K2_CONTRACT = Object.freeze({{\n    catalogVersion: {},\n    errors: Object.freeze([{codes}]),\n    verbs: Object.freeze({{\n",
        c.catalog_version
    ));
    for (_, rows) in widget_groups(c) {
        for v in rows {
            let cap = v.cap.as_deref().map(ts_str).unwrap_or_else(|| "null".into());
            s.push_str(&format!(
                "      {}: Object.freeze({{ cap: {cap}, reach: {}, kind: {}, feature: {} }}),\n",
                ts_str(&v.verb),
                ts_str(reach_name(v)),
                ts_str(kind_name(v.kind)),
                ts_str(&v.feature)
            ));
        }
    }
    s.push_str("    }),\n  })\n");
    match runtime {
        Some(rt) => {
            s.push_str(&format!("  // ---- {RUNTIME_JS} ----\n"));
            for line in rt.lines() {
                if line.is_empty() {
                    s.push('\n');
                } else {
                    s.push_str(&format!("  {line}\n"));
                }
            }
        }
        None => s.push_str(&format!("  // {RUNTIME_JS} isn't in this tree yet: the table only.\n  void K2_CONTRACT\n")),
    }
    s.push_str("})()\n");
    s
}

// ── k2 zen guide api ─────────────────────────────────────────────────────

/// The guide page text (no shell wrapping).
pub fn guide_api_page(c: &Catalog) -> String {
    let mut s = String::new();
    s.push_str("k2 zen guide api — the k2 object in a custom widget\n\n");
    s.push_str(&format!(
        "A custom widget is a sealed page in a Garden: no network, no storage, no\n\
files. It reaches K2 only through window.k2. Each call needs a cap its\n\
manifest.json asks for; a widget in your own Garden gets every one it asks\n\
for at once (no review). From K2's verb catalog, version {}.\n\n",
        c.catalog_version
    ));
    s.push_str("TEN EXAMPLES\n");
    for e in GUIDE_EXAMPLES {
        s.push_str(&format!("  {e}\n"));
    }
    s.push_str(
        "\nEVERY HELPER, BY CAP (portable: the same call works in an App later;\n\
local: Garden only). Each line: helper, reach, feature, example, [errors]\n",
    );
    let groups = widget_groups(c);
    let w_sig = groups.iter().flat_map(|(_, r)| r.iter()).map(|v| signature(v).len()).max().unwrap_or(0) + 3;
    let w_feat = groups.iter().flat_map(|(_, r)| r.iter()).map(|v| v.feature.len()).max().unwrap_or(0);
    for (cap, rows) in &groups {
        let sentence = cap.and_then(|n| c.cap(n)).map(|r| format!(" ({})", r.label)).unwrap_or_default();
        s.push_str(&format!("{}{sentence}\n", cap.unwrap_or("no cap")));
        for v in rows {
            let errs: Vec<&str> = v.errors.iter().map(String::as_str).filter(|e| !ALWAYS_ERRORS.contains(e)).collect();
            let errs = if errs.is_empty() { String::new() } else { format!("  [{}]", errs.join(" ")) };
            s.push_str(&format!(
                "  {:<w_sig$} {:<8} {:<w_feat$}  {}{errs}\n",
                format!("k2.{}", signature(v)),
                reach_name(v),
                v.feature,
                v.example
            ));
        }
    }
    s.push_str(&format!("\nEvery call may also fail with {}.\n\n", ALWAYS_ERRORS.join(", ")));
    for line in [
        "ALSO ON k2",
        "  k2.call(verb, ...args), k2.subscribe(verb, ...args, cb) (alias k2.on):",
        "  the same verbs by name. k2.can(verb): advice for drawing; K2 still",
        "  checks every call. k2.ready() once drawn. k2.config, k2.widget,",
        "  k2.asset(name), k2.motion.reduced. A refused call rejects with K2Error",
        "  (.code, .message, .verb, .cap, .room, .feature). Subscribes return the",
        "  unsubscribe; pass onError after cb (k2.thread.subscribe(addr, cb,",
        "  onError)) to hear a refused subscription (it ends; without onError K2",
        "  logs it as a widget error).",
        "",
        "RULES",
        "  textContent for anything an agent wrote, never innerHTML. No onclick=:",
        "  use addEventListener in a script file. Files via k2.asset(). Check with",
        "  k2 zen validate --widget <name>; it works as soon as it's placed.",
        "  Posting pauses after 120 posts (or 20 identical ones to one agent) in",
        "  10 minutes, until the person clicks Resume on the widget (sending_off).",
        "",
        "Types: sdk/generated/k2.d.ts in the K2 repo. Caps in K2's words: the",
        "k2-zen skill.",
    ] {
        s.push_str(line);
        s.push('\n');
    }
    s
}

fn cli_block(c: &Catalog) -> String {
    let page = guide_api_page(c);
    assert!(!page.contains("\nEOF\n"), "the guide page can't hold a heredoc terminator");
    format!(
        "{CLI_BEGIN} (do not edit; {REGEN})\n\
_zen_guide_page_api() {{\n    cat <<'EOF'\n{page}EOF\n}}\n{CLI_END}\n"
    )
}

// ── contract-snapshot.json ───────────────────────────────────────────────

fn snapshot_json(c: &Catalog, runtime: Option<&str>, outs: &[Output]) -> String {
    // Written by hand (not a serde Map) so the key order never depends on
    // serde_json's features.
    let q = |s: &str| J::String(s.to_string()).to_string();
    let mut files: Vec<(&str, String)> = outs.iter().map(|o| (o.path, sha256_hex(o.text.as_bytes()))).collect();
    files.sort();
    let runtime = runtime.map(|r| q(&sha256_hex(r.as_bytes()))).unwrap_or_else(|| "null".into());
    let files = files.iter().map(|(p, h)| format!("    {}: {}", q(p), q(h))).collect::<Vec<_>>().join(",\n");
    format!(
        "{{\n  \"generatedBy\": \"contract-gen\",\n  \"regen\": \"cargo run -p k2-core --bin contract-gen\",\n  \"catalogVersion\": {},\n  \"catalogSha256\": {},\n  \"runtimeSha256\": {runtime},\n  \"files\": {{\n{files}\n  }}\n}}\n",
        c.catalog_version,
        q(&sha256_hex(CATALOG_JSON.as_bytes())),
    )
}

