#!/usr/bin/env python3
"""Live probe for Email Notifications part 2 (prd-email-notifications-part2-v1,
vs-live EN-A25, EN-A27, EN-A29 d), against a throwaway Stalwart.

  W  the delivery webhook as K2 writes it (x:WebHook with signatureKey,
     eventsPolicy include, K2's event list, the X-K2-Key-Id header,
     throttle 100 ms), live after one ReloadSettings:
       W1 a K2-style submit (ENVID=<log id>) gives
          queue.authenticated-message-queued with a queueId
       W2 X-Signature is base64(HMAC-SHA256(key, body))
       W3 queueId -> registry id (Stalwart's base32) -> x:QueuedMessage/get
          -> envId is the ENVID K2 set (while the message is queued)
       W4 what x:WebHook/get gives back (K2 compares url, events, policy,
          the key-id header and throttle; never the key)
  S  P4b (d): does the spam filter score a K2 message up when its header
     From is a domain the box doesn't host (send-only apex) rather than the
     hosted bounce subdomain? Stalwart's x:Action ClassifySpam on the same
     message with From apex vs From bounce, authenticated and not. DNS
     blocklists and Pyzor are switched off first so the check asks no
     outside service (only the resolver, for .test names that don't exist).
     Also records the stock enableSpamFilter rule (authenticated mail isn't
     filtered by the box at all).

Nothing leaves the box: `.test` names have no MX, so queued messages wait
and are destroyed at the end. Only throwaway principals.

    STALWART_PROBE_ADMIN='admin@example.test:<secret>' \\
      python3 -I tests/mail/stalwart-notify-probe.py --url http://127.0.0.1:18080

Run it with tests/mail/stalwart-sandbox-forward-gap.sh
(STALWART_PROBE=stalwart-notify-probe.py).
"""

import argparse
import base64
import email.utils
import hashlib
import hmac
import http.server
import json
import os
import secrets
import sys
import threading
import time
import urllib.error
import urllib.request

CORE = "urn:ietf:params:jmap:core"
MAIL = "urn:ietf:params:jmap:mail"
SUBMISSION = "urn:ietf:params:jmap:submission"
REGISTRY = "urn:stalwart:jmap"
SENDER_DISABLED = ["authenticate", "authenticateWithAlias", "imapAuthenticate", "pop3Authenticate", "sieveAuthenticate", "emailSend"]
APEX = "brand.test"
BOUNCE = "bounce.brand.test"
# K2's list (crates/k2-daemon/src/email_notify/webhook.rs EVENTS).
EVENTS = [
    "queue.authenticated-message-queued", "queue.autogenerated-queued", "queue.rescheduled",
    "delivery.delivered", "delivery.completed", "delivery.failed", "delivery.rcpt-to-rejected",
    "delivery.rcpt-to-failed", "delivery.dsn-success", "delivery.dsn-temp-fail", "delivery.dsn-perm-fail",
]
ALPHABET = b"abcdefghijklmnopqrstuvwxyz792013"

FAILED = []


def check(step, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {step}: {detail}", flush=True)
    if not ok:
        FAILED.append(step)


def info(step, detail=""):
    print(f"[INFO] {step}: {detail}", flush=True)


def registry_id(n):
    """Stalwart's Id::as_string (K2's webhook::registry_id)."""
    if n == 0:
        return "a"
    m = (1 << 64) - 1
    out = ""
    top = n >> 60
    n = ((n << 4) & m) | 1
    if top == 0:
        n = (n << ((64 - n.bit_length()) // 5 * 5)) & m
    else:
        out += chr(ALPHABET[top])
    while n != (1 << 60):
        out += chr(ALPHABET[n >> 59])
        n = (n << 5) & m
    return out


class Client:
    def __init__(self, base, basic=None, bearer=None):
        self.base = base.rstrip("/")
        self.auth = ("Basic " + base64.b64encode(f"{basic[0]}:{basic[1]}".encode()).decode()) if basic else f"Bearer {bearer}"
        self._s = None

    def _req(self, method, url, body=None):
        url = url if url.startswith("http") else self.base + url
        data = json.dumps(body).encode() if body is not None else None
        r = urllib.request.Request(url, data=data, method=method)
        r.add_header("Authorization", self.auth)
        if data is not None:
            r.add_header("Content-Type", "application/json")
        try:
            with urllib.request.urlopen(r, timeout=30) as x:
                return x.status, json.loads(x.read() or b"null")
        except urllib.error.HTTPError as e:
            return e.code, {"httpError": e.code, "body": e.read().decode(errors="replace")[:300]}

    def session(self):
        if self._s is None:
            st, s = self._req("GET", "/jmap/session")
            if st != 200:
                raise RuntimeError(f"session {st}: {s}")
            self._s = s
        return self._s

    def api(self):
        p = self.session()["apiUrl"]
        return "/" + p.split("://", 1)[1].split("/", 1)[1] if p.startswith("http") else p

    def own(self):
        prim = self.session().get("primaryAccounts", {})
        return prim.get(REGISTRY) or prim.get(MAIL) or next(iter(self.session()["accounts"]))

    def batch(self, using, calls):
        st, r = self._req("POST", self.api(), {"using": list(using), "methodCalls": calls})
        if st != 200:
            return [["http", r, "0"]]
        return r["methodResponses"]

    def call(self, method, args, using=(CORE, REGISTRY)):
        if "accountId" not in args:
            args = dict(args, accountId=self.own())
        first = self.batch(using, [[method, args, "0"]])[0]
        return first[0], first[1]


class Hook(http.server.BaseHTTPRequestHandler):
    got = []

    def do_POST(self):
        n = int(self.headers.get("Content-Length") or 0)
        body = self.rfile.read(n)
        Hook.got.append((dict(self.headers), body))
        self.send_response(200)
        self.send_header("Content-Length", "2")
        self.end_headers()
        self.wfile.write(b"{}")

    def log_message(self, *a):
        pass


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--url", required=True)
    ap.add_argument("--domain")
    args = ap.parse_args()
    cred = os.environ.get("STALWART_PROBE_ADMIN", "")
    if ":" not in cred:
        sys.exit("set STALWART_PROBE_ADMIN")
    user, pw = cred.split(":", 1)
    domain = args.domain or user.split("@", 1)[-1]
    tag = secrets.token_hex(3)
    admin = Client(args.url, basic=(user, pw))

    def account(client, name, did, perms=None, password=True, admin_role=False):
        acct = {"@type": "User", "name": name, "domainId": did}
        if password:
            acct["credentials"] = {"0": {"@type": "Password", "secret": secrets.token_urlsafe(24)}}
        if admin_role:
            acct["roles"] = {"@type": "Admin"}
        else:
            acct["quotas"] = {"maxDiskQuota": 52428800, "maxEmails": 1000}
        if perms is not None:
            acct["permissions"] = perms
        n, a = client.call("x:Account/set", {"create": {"k": acct}})
        cid = ((a.get("created") or {}).get("k") or {}).get("id") if n == "x:Account/set" else None
        if not cid:
            sys.exit(f"account {name}: {n} {json.dumps(a)[:300]}")
        return cid

    n, a = admin.call("x:Domain/query", {"filter": {"name": domain}})
    did = a["ids"][0]
    svc_id = account(admin, f"k2np-svc-{tag}", did, admin_role=True)
    n, a = admin.call("x:ApiKey/set", {"accountId": svc_id, "create": {"k": {"description": "k2", "permissions": {"@type": "Inherit"}, "allowedIps": {}}}})
    svc = Client(args.url, bearer=a["created"]["k"]["secret"])

    n, a = svc.call("x:Domain/set", {"create": {"d": {"name": BOUNCE, "dkimManagement": {"@type": "Automatic"},
                                                     "subAddressing": {"@type": "Enabled"}, "catchAllAddress": None}}})
    bid = ((a.get("created") or {}).get("d") or {}).get("id")
    check("setup: bounce subdomain added", bool(bid), f"{n} {json.dumps(a)[:200]}")
    perms = {"@type": "Merge", "enabledPermissions": {}, "disabledPermissions": {p: True for p in SENDER_DISABLED}}
    sender = account(svc, "noreply", bid, perms=perms, password=False)
    sender_addr = f"noreply@{BOUNCE}"

    # 0.16.10 refuses every reload while the downloaded spam rules call
    # `bit_and` (K2's A4 repair rewrites them on a real box): drop them here.
    n, q = svc.call("x:SpamDnsblServer/query", {})
    if q.get("ids"):
        n, g = svc.call("x:SpamDnsblServer/get", {"ids": q["ids"]})
        bad = [x["id"] for x in (g.get("list") or []) if "bit_and" in json.dumps(x)]
        if bad:
            n, a = svc.call("x:SpamDnsblServer/set", {"destroy": bad})
            info("sandbox: spam rules calling bit_and dropped", f"{len(bad)}: {n}")

    # ── W: the webhook ───────────────────────────────────────────────
    srv = http.server.HTTPServer(("127.0.0.1", 0), Hook)
    port = srv.server_address[1]
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    key = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode().rstrip("=")
    key_id = hashlib.sha256(key.encode()).hexdigest()[:16]
    url = f"http://127.0.0.1:{port}/cli/email/events"
    hook = {
        "url": url, "enable": True, "eventsPolicy": "include", "events": {e: True for e in EVENTS},
        "signatureKey": {"@type": "Value", "secret": key}, "httpHeaders": {"X-K2-Key-Id": key_id},
        "throttle": 100, "timeout": 5000, "lossy": False, "allowInvalidCerts": False,
    }
    n, a = svc.call("x:WebHook/set", {"create": {"w": hook}})
    wid = ((a.get("created") or {}).get("w") or {}).get("id")
    check("W setup: x:WebHook created as K2 writes it", bool(wid), f"{n} {json.dumps(a)[:300]}")
    n, a = svc.call("x:Action/set", {"create": {"r": {"@type": "ReloadSettings"}}})
    info("W reload", f"{n} {json.dumps(a)[:200]}")
    n, g = svc.call("x:WebHook/get", {"ids": [wid]} if wid else {})
    back = (g.get("list") or [{}])[0]
    info("W4 x:WebHook/get gives back", json.dumps(back)[:900])
    check("W4 the key is never given back", key not in json.dumps(back), "")
    check("W4 url, policy, events, key-id header and throttle read back as written",
          back.get("url") == url and str(back.get("eventsPolicy", "")).lower() == "include"
          and sorted(k for k, v in (back.get("events") or {}).items() if v) == sorted(EVENTS)
          and (back.get("httpHeaders") or {}).get("X-K2-Key-Id") == key_id and back.get("throttle") == 100,
          json.dumps({k: back.get(k) for k in ("url", "eventsPolicy", "httpHeaders", "throttle")}))

    def submit(acct, mail_from, header_from, rcpt, envid):
        n, a = svc.call("Identity/get", {"accountId": acct, "ids": None}, using=(CORE, MAIL, SUBMISSION))
        ident = next((i["id"] for i in (a.get("list") or []) if i.get("email", "").lower() == mail_from), None)
        if not ident:
            n, a = svc.call("Identity/set", {"accountId": acct, "create": {"i": {"email": mail_from}}}, using=(CORE, MAIL, SUBMISSION))
            ident = ((a.get("created") or {}).get("i") or {}).get("id")
        boxes = None
        for role in ("drafts", "inbox"):
            n, q = svc.call("Mailbox/query", {"accountId": acct, "filter": {"role": role}}, using=(CORE, MAIL))
            if q.get("ids"):
                boxes = q["ids"][0]
                break
        email_ = {"mailboxIds": {boxes: True}, "from": [{"email": header_from, "name": "Brand"}], "to": [{"email": rcpt}],
                  "subject": f"probe {envid}", "bodyValues": {"t": {"value": "probe"}}, "textBody": [{"partId": "t", "type": "text/plain"}]}
        resp = svc.batch((CORE, MAIL, SUBMISSION), [
            ["Email/set", {"accountId": acct, "create": {"e": email_}}, "0"],
            ["EmailSubmission/set", {"accountId": acct, "create": {"s": {
                "emailId": "#e", "identityId": ident,
                "envelope": {"mailFrom": {"email": mail_from, "parameters": {"RET": "HDRS", "ENVID": envid}}, "rcptTo": [{"email": rcpt}]}}},
                "onSuccessDestroyEmail": ["#s"]}, "1"],
        ])
        for m in resp:
            if m[0] == "EmailSubmission/set":
                return bool((m[1].get("created") or {}).get("s")), json.dumps(m[1])[:300]
        return False, json.dumps(resp)[:300]

    envid = f"enl_probe{tag}"
    t0 = time.time()
    ok, detail = submit(sender, sender_addr, f"noreply@{APEX}", "someone@outside.test", envid)
    check("W1 setup: K2-style submit accepted", ok, detail)
    queued = None
    deadline = time.time() + 20
    while time.time() < deadline and queued is None:
        for headers, body in list(Hook.got):
            try:
                ev = json.loads(body).get("events") or []
            except ValueError:
                continue
            for e in ev:
                d = e.get("data") or {}
                if e.get("type") == "queue.authenticated-message-queued" and str(d.get("from", "")).lower().strip("<>") == sender_addr:
                    queued = (headers, body, e)
        time.sleep(0.1)
    check("W1 queue.authenticated-message-queued arrived with a queueId",
          queued is not None and "queueId" in (queued[2].get("data") or {}),
          f"after {time.time() - t0:.2f}s; {len(Hook.got)} batch(es)" + (f"; {json.dumps(queued[2])[:400]}" if queued else ""))
    if queued:
        headers, body, e = queued
        sig = next((v for k, v in headers.items() if k.lower() == "x-signature"), None)
        want = base64.b64encode(hmac.new(key.encode(), body, hashlib.sha256).digest()).decode()
        check("W2 X-Signature is base64 HMAC-SHA256 of the body under the key", sig == want, f"got {sig!r}")
        check("W2 the X-K2-Key-Id header rides along", next((v for k, v in headers.items() if k.lower() == "x-k2-key-id"), None) == key_id, "")
        qid = e["data"]["queueId"]
        info("W3 queueId JSON type", type(qid).__name__)
        rid = registry_id(int(qid))
        # The queued event is emitted just before the message is written to
        # the queue: ask at once, then after K2's waits (200, 500, 1000 ms).
        tries = []
        got = {}
        for wait_ms in (0, 200, 500, 1000):
            time.sleep(wait_ms / 1000)
            n, g = svc.call("x:QueuedMessage/get", {"ids": [rid], "properties": ["id", "envId"]})
            got = (g.get("list") or [{}])[0]
            tries.append("found" if got.get("envId") else "missing")
            if got.get("envId"):
                break
        info("W3 lookups (at once, then after 200/500/1000 ms)", " ".join(tries))
        check("W3 queueId -> registry id -> x:QueuedMessage envId is K2's ENVID (with K2's retries)", got.get("envId") == envid, f"{rid}: {json.dumps(g)[:300]}")
    # A local delivery (sender to a box mailbox): which events, does it carry the queue id?
    mbox = account(svc, f"bob{tag}", did)
    before = len(Hook.got)
    ok, detail = submit(sender, sender_addr, f"noreply@{APEX}", f"bob{tag}@{domain}", f"enl_local{tag}")
    time.sleep(3)
    kinds = []
    for _, body in Hook.got[before:]:
        for e in json.loads(body).get("events") or []:
            kinds.append((e.get("type"), sorted((e.get("data") or {}).keys())))
    info("W local delivery events (type, data keys)", json.dumps(kinds)[:900])
    _ = mbox

    # ── S: P4b (d) spam score ───────────────────────────────────────
    n, g = svc.call("x:MtaStageData/get", {"ids": ["singleton"], "properties": ["enableSpamFilter"]})
    info("S stock enableSpamFilter (authenticated mail is not filtered when it says is_empty(authenticated_as))",
         json.dumps((g.get("list") or [{}])[0])[:300])
    # The DNSBL limits can't be 0 (MinValue 1), so drop every blocklist
    # server in this throwaway sandbox instead: no blocklist is asked.
    n, q = svc.call("x:SpamDnsblServer/query", {})
    ids = q.get("ids") or []
    if ids:
        n, a = svc.call("x:SpamDnsblServer/set", {"destroy": ids})
        left = svc.call("x:SpamDnsblServer/query", {})[1].get("ids") or []
        check("S DNS blocklists off (no outside lookups)", not left, f"{len(ids)} destroyed, {len(left)} left: {n}")
    n, a = svc.call("x:SpamPyzor/set", {"update": {"singleton": {"enable": False}}})
    info("S Pyzor off (no outside lookups)", f"{n} {json.dumps(a)[:160]}")
    n, a = svc.call("x:Action/set", {"create": {"r": {"@type": "ReloadSettings"}}})
    info("S reload", f"{n} {json.dumps(a)[:160]}")

    def message(from_addr):
        return (f"From: Brand <{from_addr}>\r\nTo: someone@outside.test\r\nSubject: Your sign-in code\r\n"
                # K2's Message-ID is on the From's domain (mail::send::new_message_id_for).
                f"Date: {email.utils.formatdate(localtime=False)}\r\nMessage-ID: <k2.{tag}@{from_addr.split('@')[1]}>\r\n"
                "MIME-Version: 1.0\r\nContent-Type: text/plain; charset=utf-8\r\n\r\n"
                "Your sign-in code is 482913. It expires in 10 minutes.\r\n\r\n--\r\nSent by K2 for Brand.\r\n")

    def classify(from_addr, authed):
        req = {"@type": "ClassifySpam", "message": message(from_addr), "remoteIp": "127.0.0.1", "ehloDomain": "mail.example.test",
               "authenticatedAs": sender_addr if authed else None, "isTls": True, "envFrom": sender_addr,
               "envRcptTo": {"someone@outside.test": True}}
        n, a = svc.call("x:Action/set", {"create": {"c": req}})
        c = (a.get("created") or {}).get("c")
        if not c:
            return None, f"{n} {json.dumps(a)[:400]}"
        return c, json.dumps(c)[:1200]

    results = {}
    for label, frm in (("apex", f"noreply@{APEX}"), ("bounce", sender_addr)):
        for authed in (False, True):
            c, raw = classify(frm, authed)
            results[(label, authed)] = c
            info(f"S classify From {label} ({'authenticated' if authed else 'unauthenticated'})", raw)
    if any(v is None for v in results.values()):
        check("S ClassifySpam answered", False, "see above (this Stalwart may not have the action)")
    else:
        for authed in (False, True):
            a_, b_ = results[("apex", authed)], results[("bounce", authed)]
            sa, sb = float(a_.get("score") or 0), float(b_.get("score") or 0)
            extra = sorted(set((a_.get("tags") or {}).keys()) - set((b_.get("tags") or {}).keys()))
            missing = sorted(set((b_.get("tags") or {}).keys()) - set((a_.get("tags") or {}).keys()))
            mode = "authenticated" if authed else "unauthenticated"
            info(f"S {mode}: score apex {sa} vs bounce {sb} (result {a_.get('result')} / {b_.get('result')})",
                 f"tags only on apex {extra}; only on bounce {missing}")
            check(f"S {mode}: an unhosted From scores no higher than the hosted bounce From", sa <= sb, f"{sa} vs {sb}")

    # Tidy.
    if wid:
        svc.call("x:WebHook/set", {"destroy": [wid]})
    n, q = svc.call("x:QueuedMessage/query", {})
    if q.get("ids"):
        svc.call("x:QueuedMessage/set", {"destroy": q["ids"]})
    srv.shutdown()
    print(f"== notify probe: {len(FAILED)} failed check(s): {FAILED} ==", flush=True)
    sys.exit(1 if FAILED else 0)


if __name__ == "__main__":
    main()
