pub fn url_for(port: u16) -> String {
    format!("http://127.0.0.1:{port}{EVENTS_PATH}")
}

/// Is this webhook K2's own (any port: the daemon's port can move)?
pub fn is_ours(obj: &J) -> bool {
    obj.get("url")
        .and_then(J::as_str)
        .is_some_and(|u| u.starts_with("http://127.0.0.1:") && u.ends_with(EVENTS_PATH))
}

/// The full object K2 writes.
pub fn desired(port: u16, key: &str) -> J {
    let events: serde_json::Map<String, J> = EVENTS.iter().map(|e| (e.to_string(), J::Bool(true))).collect();
    json!({
        "url": url_for(port),
        "enable": true,
        "eventsPolicy": "include",
        "events": events,
        "signatureKey": { "@type": "Value", "secret": key },
        "httpHeaders": { KEY_ID_HEADER: key_id(key) },
        "throttle": THROTTLE_MS,
        "timeout": TIMEOUT_MS,
        "lossy": false,
        "allowInvalidCerts": false,
    })
}

/// Does `obj` (as read back) differ from what K2 wants?
pub fn differs(obj: &J, port: u16, key: &str) -> bool {
    let events: std::collections::BTreeSet<&str> = match obj.get("events").and_then(J::as_object) {
        Some(m) => m.iter().filter(|(_, v)| v.as_bool() != Some(false)).map(|(k, _)| k.as_str()).collect(),
        None => std::collections::BTreeSet::new(),
    };
    let want: std::collections::BTreeSet<&str> = EVENTS.iter().copied().collect();
    let header_id = obj.get("httpHeaders").and_then(|h| h.get(KEY_ID_HEADER)).and_then(J::as_str);
    obj.get("url").and_then(J::as_str) != Some(url_for(port).as_str())
        || obj.get("enable").and_then(J::as_bool) == Some(false)
        || !obj.get("eventsPolicy").and_then(J::as_str).is_some_and(|p| p.eq_ignore_ascii_case("include"))
        || events != want
        || header_id != Some(key_id(key).as_str())
        || obj.get("throttle").and_then(J::as_u64).is_some_and(|t| t != THROTTLE_MS)
}

