#!/usr/bin/env bash
# audit-canary.sh <tooldir> — proves the advisory scanners in `checks.sh
# audit` still fail on a known advisory, that an allow-list entry lets it
# through, and that an expired entry doesn't (prd-security-sweep-0464-v1
# T14). Without this, a scanner that silently checks nothing (no database,
# a parser change) would look green.
#
# <tooldir> holds bin/cargo-audit and osv-scanner (checks.sh audit installs
# them). The fixture lock is written to a temp dir at run time, so no
# vulnerable lockfile is checked in. Needs the internet (RustSec database,
# osv.dev). The allow-list rules are tested offline at the end. No skips.
set -euo pipefail

T="$(cd "${1:?usage: audit-canary.sh <tooldir>}" && pwd)"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
CARGO_AUDIT="$T/bin/cargo-audit"
OSV="$T/osv-scanner"
[ -x "$CARGO_AUDIT" ] || { echo "audit-canary: no $CARGO_AUDIT" >&2; exit 1; }
[ -x "$OSV" ] || { echo "audit-canary: no $OSV" >&2; exit 1; }

pass=0
fail=0
pass() { echo "  PASS: $1"; pass=$((pass + 1)); }
fail() { echo "  FAIL: $1" >&2; echo "        $2" >&2; fail=$((fail + 1)); }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/lock"
# smallvec 1.6.0: RUSTSEC-2021-0003 (GHSA-43w2-9j62-hq99), fixed in 1.6.1.
cat > "$tmp/lock/Cargo.lock" <<'LOCK'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "smallvec"
version = "1.6.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
LOCK
ADV=RUSTSEC-2021-0003
ALIAS=GHSA-43w2-9j62-hq99

echo "cargo audit:"
rc=0; out="$(cd "$tmp/lock" && "$CARGO_AUDIT" audit --deny warnings --file Cargo.lock 2>&1)" || rc=$?
[ "$rc" != 0 ] && [[ "$out" == *"$ADV"* ]] && pass "fails on $ADV" || fail "cargo audit missed $ADV" "rc=$rc $out"
rc=0; out="$(cd "$tmp/lock" && "$CARGO_AUDIT" audit --deny warnings --file Cargo.lock --ignore "$ADV" 2>&1)" || rc=$?
[ "$rc" = 0 ] && pass "an ignore entry lets it through" || fail "cargo audit ignore" "rc=$rc $out"

echo "osv-scanner:"
rc=0; out="$("$OSV" scan source --lockfile "$tmp/lock/Cargo.lock" 2>&1)" || rc=$?
[ "$rc" = 1 ] && { [[ "$out" == *"$ADV"* ]] || [[ "$out" == *"$ALIAS"* ]]; } && pass "fails on $ADV (exit 1)" || fail "osv-scanner missed $ADV" "rc=$rc $out"
future="$(python3 -c 'import datetime as d; print((d.date.today() + d.timedelta(days=30)).isoformat())')"
past="$(python3 -c 'import datetime as d; print((d.date.today() - d.timedelta(days=1)).isoformat())')"
for id in "$ADV" "$ALIAS"; do
    printf '[[IgnoredVulns]]\nid = "%s"\nignoreUntil = %sT00:00:00Z\nreason = "canary: a known advisory in a throwaway lock"\n\n' "$id" "$future" >> "$tmp/ok.toml"
    printf '[[IgnoredVulns]]\nid = "%s"\nignoreUntil = %sT00:00:00Z\nreason = "canary: a known advisory in a throwaway lock"\n\n' "$id" "$past" >> "$tmp/expired.toml"
done
rc=0; out="$("$OSV" scan source --lockfile "$tmp/lock/Cargo.lock" --config "$tmp/ok.toml" 2>&1)" || rc=$?
[ "$rc" = 0 ] && pass "an ignore entry lets it through" || fail "osv-scanner ignore" "rc=$rc $out"
rc=0; out="$("$OSV" scan source --lockfile "$tmp/lock/Cargo.lock" --config "$tmp/expired.toml" 2>&1)" || rc=$?
[ "$rc" = 1 ] && pass "an expired entry doesn't" || fail "osv-scanner expired ignore" "rc=$rc $out"

echo "allow-list rules (scripts/ci/audit-ignores.py, offline):"
check() { python3 "$ROOT/scripts/ci/audit-ignores.py" check --today 2026-10-24 --osv "$tmp/$1.osv.toml" --cargo "$tmp/$1.cargo.toml" 2>&1; }
entry() { printf '[[IgnoredVulns]]\nid = "%s"\nignoreUntil = %s\nreason = "%s"\n\n' "$1" "$2" "$3"; }
R="not reachable: the crate is only used by the build script"
entry RUSTSEC-2026-0001 2026-12-01T00:00:00Z "$R" > "$tmp/good.osv.toml"
entry GHSA-aaaa-bbbb-cccc 2027-01-22T00:00:00Z "$R" >> "$tmp/good.osv.toml"
printf '[advisories]\nignore = ["RUSTSEC-2026-0001"]\n' > "$tmp/good.cargo.toml"
rc=0; out="$(check good)" || rc=$?
[ "$rc" = 0 ] && pass "a good list passes" || fail "good list" "rc=$rc $out"
bad_case() {
    local name="$1" want="$2"
    local rc=0 out
    out="$(check "$name")" || rc=$?
    [ "$rc" = 1 ] && [[ "$out" == *"$want"* ]] && pass "$name refused" || fail "$name not refused" "rc=$rc $out"
}
entry RUSTSEC-2026-0001 2026-10-24T00:00:00Z "$R" > "$tmp/expired.osv.toml"; cp "$tmp/good.cargo.toml" "$tmp/expired.cargo.toml"
bad_case expired "expired on 2026-10-24"
entry RUSTSEC-2026-0001 2027-01-23T00:00:00Z "$R" > "$tmp/far.osv.toml"; cp "$tmp/good.cargo.toml" "$tmp/far.cargo.toml"
bad_case far "more than 90 days out"
entry RUSTSEC-2026-0001 2026-12-01T00:00:00Z "later" > "$tmp/noreason.osv.toml"; cp "$tmp/good.cargo.toml" "$tmp/noreason.cargo.toml"
bad_case noreason "needs a reason"
printf '[[IgnoredVulns]]\nid = "RUSTSEC-2026-0001"\nreason = "%s"\n' "$R" > "$tmp/nodate.osv.toml"; cp "$tmp/good.cargo.toml" "$tmp/nodate.cargo.toml"
bad_case nodate "needs ignoreUntil"
{ entry RUSTSEC-2026-0001 2026-12-01T00:00:00Z "$R"; entry RUSTSEC-2026-0001 2026-12-01T00:00:00Z "$R"; } > "$tmp/twice.osv.toml"; cp "$tmp/good.cargo.toml" "$tmp/twice.cargo.toml"
bad_case twice "listed twice"
cp "$tmp/good.osv.toml" "$tmp/orphan.osv.toml"; printf '[advisories]\nignore = ["RUSTSEC-2026-0002"]\n' > "$tmp/orphan.cargo.toml"
bad_case orphan "RUSTSEC-2026-0002 has no entry"

echo ""
echo "audit-canary: $pass passed, $fail failed"
[ "$fail" = 0 ]
