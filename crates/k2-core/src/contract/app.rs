/// The generated `sdk/server/src/generated/verbs.ts`.
pub fn sdk_verbs_ts(c: &Catalog) -> Result<String, String> {
    let mut ts = Ts::default();
    let mut table = Vec::new();
    let mut verbs_map = Vec::new();
    let mut calls = Vec::new();
    let mut subs = Vec::new();
    let mut surface_order: Vec<&str> = Vec::new();
    let mut surfaces: std::collections::BTreeMap<&str, Vec<String>> = std::collections::BTreeMap::new();
    for v in rows(c) {
        let cap = v.cap.as_deref().map(ts_str).unwrap_or_else(|| "null".into());
        let effect = if v.effect == Effect::Write { "write" } else { "read" };
        let (http, door, names) = match &v.bindings.http {
            Some(h) => {
                let method = if h.method == HttpMethod::Get { "GET" } else { "POST" };
                let query = h.query.iter().map(|q| ts_str(q)).collect::<Vec<_>>().join(", ");
                (
                    format!("{{ method: {}, route: {}, params: {}, query: [{query}] }}", ts_str(method), ts_str(&h.route), ts_record(&h.params)),
                    door_name(h.door),
                    ts_record(&h.response_names),
                )
            }
            None => ("null".into(), "both", "{}".into()),
        };
        let socket = match &v.bindings.socket {
            Some(s) => format!(
                "{{ path: {}, param: {}, frame: {}, refetch: {}, query: {} }}",
                ts_str(&s.path),
                ts_str(s.param.as_deref().unwrap_or("")),
                ts_str(&s.frame),
                s.refetch.as_deref().map(ts_str).unwrap_or_else(|| "null".into()),
                ts_record(&s.query)
            ),
            None => "null".into(),
        };
        table.push(format!(
            "  {}: {{\n    cap: {cap},\n    effect: {},\n    kind: {},\n    feature: {},\n    door: {},\n    http: {http},\n    socket: {socket},\n    responseNames: {names},\n    response: {},\n  }},\n",
            ts_str(&v.verb),
            ts_str(effect),
            ts_str(kind_name(v.kind)),
            ts_str(&v.feature),
            ts_str(door),
            canon(&projection_schema(&v.response)),
        ));
        let args = match request_items(v).first() {
            Some(a) => {
                let t = ts.arg(a)?;
                if a.get("default").is_some() {
                    format!("args?: {t}")
                } else {
                    format!("args: {t}")
                }
            }
            None => "args?: Record<string, never>".into(),
        };
        let arg_type = match request_items(v).first() {
            Some(a) => ts.arg(a)?,
            None => "Record<string, never>".into(),
        };
        let value = ts.ty(&v.response)?;
        verbs_map.push(format!("  {}: {{ args: {arg_type}; value: {value} }}", ts_str(&v.verb)));
        // A browser-only row (a guest's own session) has no server helper.
        if v.bindings.http.as_ref().is_some_and(|h| h.door == Some(Door::Helper)) {
            continue;
        }
        let (surface, action) = v.verb.split_once('.').expect("lint checked surface.action");
        if !surface_order.contains(&surface) {
            surface_order.push(surface);
        }
        let method = match v.kind {
            VerbKind::Subscribe => {
                subs.push(ts_str(&v.verb));
                format!("  {action}({args}, onFrame: (frame: {value}) => void, onError?: (error: K2Error) => void): () => void")
            }
            _ => {
                calls.push(ts_str(&v.verb));
                format!("  {action}({args}): Promise<{value}>")
            }
        };
        surfaces.entry(surface).or_default().push(format!("{}{method}", sdk_doc(v)));
    }
    let mut s = generated_header("//", " (rows exposed to `app`)");
    s.push_str(
        "//\n// The server SDK's verb table and types (runtime S23). `fromEnv()` builds\n// one helper per row; `call` / `subscribe` reach the same verbs by name.\n\n",
    );
    s.push_str("import type { K2Error } from '../errors.ts'\n\n");
    s.push_str(&format!("/** The catalog version this table was generated from. */\nexport const CATALOG_VERSION = {}\n\n", c.catalog_version));
    s.push_str(SDK_ROW_TYPES);
    s.push_str("/** Every App verb, in catalog order. */\nexport const APP_VERBS = {\n");
    for t in &table {
        s.push_str(t);
    }
    s.push_str("} as const satisfies Record<string, AppVerbRow>\n\n");
    s.push_str("export type AppVerb = keyof typeof APP_VERBS\n\n");
    for name in &ts.order {
        s.push_str(&ts.bodies[name]);
        s.push('\n');
    }
    let codes = c.errors.iter().map(|e| ts_str(&e.code)).collect::<Vec<_>>().join(", ");
    s.push_str(&format!("/** The shared error codes (catalog `errors`). */\nexport const APP_ERROR_CODES = [{codes}] as const\n\nexport type AppErrorCode = (typeof APP_ERROR_CODES)[number]\n\n"));
    s.push_str(&format!("/** Every App verb: its arguments and its answer (or frame). */\nexport interface AppVerbs {{\n{}\n}}\n\n", verbs_map.join("\n")));
    s.push_str(&format!(
        "export type AppCallVerb = {}\nexport type AppSubscribeVerb = {}\n\n",
        if calls.is_empty() { "never".into() } else { calls.join(" | ") },
        if subs.is_empty() { "never".into() } else { subs.join(" | ") }
    ));
    s.push_str("/** The named helpers: one per App verb a server calls (browser-only rows have none), grouped by surface. */\nexport interface AppSurfaces {\n");
    for surface in &surface_order {
        s.push_str(&format!("  readonly {surface}: {{\n"));
        for m in &surfaces[surface] {
            for line in m.lines() {
                s.push_str(&format!("  {line}\n"));
            }
        }
        s.push_str("  }\n");
    }
    s.push_str("}\n\n");
    s.push_str(&format!(
        "/** The surface names, in catalog order (the client builds one object each). */\nexport const APP_SURFACES = [{}] as const\n",
        surface_order.iter().map(|x| ts_str(x)).collect::<Vec<_>>().join(", ")
    ));
    Ok(s)
}

