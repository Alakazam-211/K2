//! `k2 study live`: the live surfaces an App or a Garden widget can show,
//! generated from the verb catalog (0.46.5 activity SDK,
//! review-thread-activity-surface-v1 §4). Rosson 2026-10-27: "so that
//! agents are more aware of what surfaces and counts are available and how
//! they can be applied in a useful way to the apps other people might
//! build around the software".
//!
//! A catalog row joins a surface with its optional `live` field
//! ([`super::LiveRow`]: `topic`, `role`, `pairs`, `counts`, `uses`,
//! `never`, `ready`). `live-topics.json` beside the catalog gives each
//! surface its title, what it tells, its ready-made helpers and its use
//! and never lines, in page order. The page shows, per surface: what it
//! tells, the caps on each side, the read and live verbs on each side (a
//! "—" is a gap, stated, never papered over), the ready-made helpers, two
//! use ideas and what never to infer. `contract-gen` writes it as the
//! fenced `_study_page_live` block in `cli/k2`; the freshness test fails
//! on drift, so the page can't fall behind the catalog.

use std::collections::BTreeSet;

use serde::Deserialize;

use super::lint::valid_verb_name;
use super::{Catalog, Exposure, LiveRole, VerbKind, VerbRow};

/// The checked-in surface list.
pub const LIVE_TOPICS_JSON: &str = include_str!("live-topics.json");
pub const LIVE_TOPICS_PATH: &str = "crates/k2-core/src/contract/live-topics.json";

/// The fence around the page in `cli/k2`.
pub const LIVE_BEGIN: &str = "# >>> generated by contract-gen: study live";
/// [`super::gen::Output::path`] key for the block (its file is `cli/k2`).
pub const LIVE_KEY: &str = "cli/k2#study live";

/// The page's line cap (k2 study pages are bounded).
pub const LIVE_MAX_LINES: usize = 150;
/// A use idea, at most this many characters (two per surface).
pub const USE_MAX_CHARS: usize = 80;
/// The never line, at most this many characters.
pub const NEVER_MAX_CHARS: usize = 100;

/// One surface (`live-topics.json`).
#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct LiveTopic {
    pub topic: String,
    /// Upper case on the page: "THREAD TURN".
    pub title: String,
    /// One line: what it answers ("what the agent is doing with a message, now").
    pub what: String,
    /// What the values tell ("state, step kind, subagents/background, elapsed").
    pub tells: String,
    /// Ready-made helpers (no catalog row): SDK helpers, libraries, elements.
    #[serde(default)]
    pub ready: Vec<String>,
    /// At most two, each ≤ [`USE_MAX_CHARS`].
    #[serde(default, rename = "use")]
    pub uses: Vec<String>,
    /// ≤ [`NEVER_MAX_CHARS`].
    #[serde(default)]
    pub never: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(deny_unknown_fields)]
struct TopicsFile {
    topics: Vec<LiveTopic>,
}

/// The checked-in topics, in page order. Panics with the path on a bad
/// file (the contract tests load it).
pub fn live_topics() -> Vec<LiveTopic> {
    serde_json::from_str::<TopicsFile>(LIVE_TOPICS_JSON)
        .unwrap_or_else(|e| panic!("{LIVE_TOPICS_PATH} does not parse: {e}"))
        .topics
}

fn app_side(v: &VerbRow) -> bool {
    v.exposed_to(Exposure::App)
}

fn garden_side(v: &VerbRow) -> bool {
    v.exposed_to(Exposure::Widget) || v.exposed_to(Exposure::GardenLocal)
}

fn rows_of<'a>(c: &'a Catalog, topic: &str) -> Vec<&'a VerbRow> {
    c.verbs
        .iter()
        .filter(|v| v.live.as_ref().is_some_and(|l| l.topic == topic || l.also_topics.iter().any(|t| t == topic)))
        .collect()
}

/// Problems with the `live` fields and the topic file (empty = clean).
pub fn lint_live(c: &Catalog, out: &mut Vec<String>) {
    let topics = live_topics();
    let mut seen = BTreeSet::new();
    for t in &topics {
        if !seen.insert(t.topic.as_str()) {
            out.push(format!("live topic {}: listed twice", t.topic));
        }
        if t.uses.len() > 2 || t.uses.iter().any(|u| u.chars().count() > USE_MAX_CHARS) {
            out.push(format!("live topic {}: at most two uses of ≤ {USE_MAX_CHARS} characters", t.topic));
        }
        if t.never.as_ref().is_some_and(|n| n.chars().count() > NEVER_MAX_CHARS) {
            out.push(format!("live topic {}: never is ≤ {NEVER_MAX_CHARS} characters", t.topic));
        }
        if rows_of(c, &t.topic).is_empty() {
            out.push(format!("live topic {}: no catalog row names it", t.topic));
        }
    }
    for v in &c.verbs {
        let Some(l) = &v.live else { continue };
        let name = &v.verb;
        if !seen.contains(l.topic.as_str()) {
            out.push(format!("{name}: live.topic '{}' isn't in {LIVE_TOPICS_PATH}", l.topic));
        }
        for t in &l.also_topics {
            if !seen.contains(t.as_str()) || *t == l.topic {
                out.push(format!("{name}: live.alsoTopics '{t}' isn't another topic in {LIVE_TOPICS_PATH}"));
            }
        }
        if v.exposure.is_empty() {
            out.push(format!("{name}: a live row is exposed (App or Garden)"));
        }
        match l.role {
            LiveRole::Read if v.kind != VerbKind::Call => out.push(format!("{name}: live.role read is a call row")),
            LiveRole::Subscribe if v.kind != VerbKind::Subscribe => out.push(format!("{name}: live.role subscribe is a subscribe row")),
            _ => {}
        }
        for p in &l.pairs {
            if !valid_verb_name(p) || c.verb(p).is_none() {
                out.push(format!("{name}: live.pairs '{p}' isn't a verb"));
            }
        }
        if l.uses.len() > 2 || l.uses.iter().any(|u| u.chars().count() > USE_MAX_CHARS) {
            out.push(format!("{name}: live.uses is at most two lines of ≤ {USE_MAX_CHARS} characters"));
        }
        if l.never.as_ref().is_some_and(|n| n.chars().count() > NEVER_MAX_CHARS) {
            out.push(format!("{name}: live.never is ≤ {NEVER_MAX_CHARS} characters"));
        }
    }
}

fn verbs_line(rows: &[&VerbRow], role: LiveRole, side: fn(&VerbRow) -> bool) -> String {
    let names: Vec<String> = rows
        .iter()
        .filter(|v| side(v) && v.live.as_ref().is_some_and(|l| l.role == role))
        .map(|v| {
            let pairs = v.live.as_ref().map(|l| l.pairs.clone()).unwrap_or_default();
            if role == LiveRole::Subscribe && !pairs.is_empty() {
                format!("{} (on open: {})", v.verb, pairs.join(", "))
            } else {
                v.verb.clone()
            }
        })
        .collect();
    if names.is_empty() {
        "—".into()
    } else {
        names.join(", ")
    }
}

fn caps_line(rows: &[&VerbRow], side: fn(&VerbRow) -> bool) -> String {
    let mut caps: Vec<&str> = Vec::new();
    for v in rows.iter().filter(|v| side(v)) {
        for cap in v.all_caps() {
            if !caps.contains(&cap) {
                caps.push(cap);
            }
        }
    }
    let any = rows.iter().any(|v| side(v));
    match (any, caps.is_empty()) {
        (false, _) => "—".into(),
        (true, true) => "none".into(),
        (true, false) => caps.join(" + "),
    }
}

/// The page text (no shell wrapping).
pub fn live_page(c: &Catalog) -> String {
    let mut s = String::new();
    s.push_str("k2 study live — live surfaces: what an App or a Garden widget can show live\n\n");
    for line in [
        "Every live surface is a READ (the state now) and a LIVE feed (what",
        "changes). Open the live feed first, read on every (re)open and REPLACE",
        "what you show, then apply changes. App = an App's server SDK",
        "(@k2/server) or its pages; Garden = a custom widget (window.k2).",
        "\"—\" = not on that side yet (a gap, not a workaround). Show only what",
        "K2 sends: never infer state from terminal output, timing or replies.",
        "",
    ] {
        s.push_str(line);
        s.push('\n');
    }
    for t in live_topics() {
        let rows = rows_of(c, &t.topic);
        let mut tells = t.tells.clone();
        let mut counts: Vec<&str> = Vec::new();
        for k in rows.iter().filter_map(|v| v.live.as_ref()).flat_map(|l| l.counts.keys()) {
            if !counts.contains(&k.as_str()) {
                counts.push(k.as_str());
            }
        }
        if !counts.is_empty() {
            tells.push_str(&format!(" (counts: {})", counts.join(", ")));
        }
        let mut ready: Vec<String> = t.ready.clone();
        for v in &rows {
            if let Some(r) = v.live.as_ref().and_then(|l| l.ready.clone()) {
                if !ready.contains(&r) {
                    ready.push(r);
                }
            }
        }
        let mut uses: Vec<String> = t.uses.clone();
        for v in &rows {
            for u in v.live.as_ref().map(|l| l.uses.clone()).unwrap_or_default() {
                if uses.len() < 2 && !uses.contains(&u) {
                    uses.push(u);
                }
            }
        }
        let never = t.never.clone().or_else(|| rows.iter().find_map(|v| v.live.as_ref().and_then(|l| l.never.clone())));
        s.push_str(&format!("{} ({})\n", t.title, t.what));
        s.push_str(&format!("  tells   {tells}\n"));
        s.push_str(&format!("  cap     App {} · Garden {}\n", caps_line(&rows, app_side), caps_line(&rows, garden_side)));
        s.push_str(&format!(
            "  read    App {} · Garden {}\n",
            verbs_line(&rows, LiveRole::Read, app_side),
            verbs_line(&rows, LiveRole::Read, garden_side)
        ));
        s.push_str(&format!(
            "  live    App {} · Garden {}\n",
            verbs_line(&rows, LiveRole::Subscribe, app_side),
            verbs_line(&rows, LiveRole::Subscribe, garden_side)
        ));
        if !ready.is_empty() {
            s.push_str(&format!("  ready   {}\n", ready.join(" · ")));
        }
        if !uses.is_empty() {
            s.push_str(&format!("  use     {}\n", uses.join(" · ")));
        }
        if let Some(n) = never {
            s.push_str(&format!("  never   {n}\n"));
        }
        s.push('\n');
    }
    s.push_str("More: k2 study apps (THREAD EAR, AGENT WORKING), k2 study app-api (every\n");
    s.push_str("App verb), k2 zen guide api (every widget verb), k2 zen guide libs.\n");
    s
}

/// The fenced `cli/k2` block: markers, the shell function, the page.
pub fn live_block(c: &Catalog) -> String {
    let page = live_page(c);
    format!(
        "{LIVE_BEGIN} (do not edit; {})\n_study_page_live() {{\n    cat <<'EOF'\n{page}EOF\n}}\n{}\n",
        super::gen::REGEN,
        super::gen::CLI_END
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::contract::catalog;

    #[test]
    fn the_live_fields_and_topics_lint_clean() {
        let mut out = Vec::new();
        lint_live(catalog(), &mut out);
        assert!(out.is_empty(), "{out:#?}");
    }

    #[test]
    fn the_page_is_bounded_and_names_both_sides_of_the_thread_turn() {
        let page = live_page(catalog());
        let lines = page.lines().count();
        assert!(lines <= LIVE_MAX_LINES, "k2 study live is {lines} lines (cap {LIVE_MAX_LINES})");
        let turn = page.split("\n\n").find(|b| b.starts_with("THREAD TURN")).expect("a THREAD TURN block");
        assert!(turn.contains("cap     App activity:read + thread:read · Garden activity:read + thread:read"), "{turn}");
        assert!(turn.contains("thread.activity") && turn.contains("thread.activityRooms") && turn.contains("thread.onActivity"), "{turn}");
        assert!(turn.contains("live    App thread.stream"), "the room stream (ear=1) is the App's live feed: {turn}");
        assert!(turn.contains("K2Activity.mount") && turn.contains("<k2-activity-bar"), "{turn}");
        assert!(turn.contains("never"), "{turn}");
        // Every topic is on the page, in the file's order.
        let mut at = 0;
        for t in live_topics() {
            let i = page[at..].find(&format!("{} (", t.title)).map(|i| i + at).unwrap_or_else(|| panic!("{} is missing", t.title));
            at = i;
        }
    }

    #[test]
    fn a_live_row_with_a_bad_topic_or_role_fails() {
        let mut c = catalog().clone();
        let v = c.verbs.iter_mut().find(|v| v.verb == "thread.activity").expect("thread.activity");
        let live = v.live.as_mut().expect("thread.activity is a live row");
        live.topic = "nope".into();
        live.role = LiveRole::Subscribe;
        let mut out = Vec::new();
        lint_live(&c, &mut out);
        assert!(out.iter().any(|p| p.contains("live.topic 'nope'")), "{out:#?}");
        assert!(out.iter().any(|p| p.contains("live.role subscribe is a subscribe row")), "{out:#?}");
    }
}
